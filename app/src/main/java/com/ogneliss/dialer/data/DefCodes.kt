package com.ogneliss.dialer.data

/**
 * Локальная таблица кодов DEF (мобильные коды РФ) → оператор.
 *
 * Это ПРИБЛИЗИТЕЛЬНОЕ определение: после отмены "мобильного рабства" (MNP)
 * абонент может перенести номер к другому оператору, сохранив код.
 * Поэтому в UI подпись выводится как «предположительно».
 *
 * Полный реестр Россвязи — около 3000 диапазонов. Здесь ядро по префиксам;
 * на этапе 5 дорожной карты таблица заменяется на упакованный в assets
 * бинарный индекс диапазонов (код + диапазон 7 цифр) с бинарным поиском.
 */
object DefCodes {

    private val map: Map<String, String> = buildMap {
        listOf("910","911","912","913","914","915","916","917","919","980","981","982","983",
               "984","985","986","987","988","989").forEach { put(it, "МТС") }

        listOf("902","904","908","950","951","952","953","958","991","992","993","994","995",
               "996","999").forEach { put(it, "Tele2") }

        listOf("900","901","903","906","909","920","921","922","923","924","925","926","927",
               "928","929","930","931","932","933","934","936","937","938","939").forEach { put(it, "Билайн / МегаФон") }

        listOf("977","978","958").forEach { put(it, "Виртуальный оператор") }
        put("800", "Бесплатная линия")
        put("809", "Платная линия")
    }

    fun operatorFor(code: String): String? = map[code]
}
