package com.ogneliss.dialer.data

/**
 * ПОСТРАНИЧНАЯ ЗАГРУЗКА ЖУРНАЛА.
 *
 * ── Почему не Paging 3 в чистом виде ───────────────────────────────────────
 *
 * Paging 3 отдаёт `PagingData` — поток страниц, который нельзя целиком
 * просмотреть в памяти. Для нашей задачи это несовместимо сразу по двум
 * причинам:
 *
 * 1. ГРАНИЦЫ СТРАНИЦ ЛОМАЮТ ГРУППИРОВКУ. В режиме «подряд идущие» последняя
 *    карточка страницы N и первая карточка страницы N+1 могут оказаться
 *    вызовами одного абонента. Их нужно склеить, а Paging обрабатывает
 *    страницы независимо. Наивная реализация даёт видимый артефакт:
 *    «Любимая (3)» и сразу под ней «Любимая (2)» вместо «Любимая (5)».
 *
 * 2. РЕЖИМ «ВСЕ ВЫЗОВЫ АБОНЕНТА» ТРЕБУЕТ ПОЛНОГО ПРОСМОТРА. Чтобы собрать
 *    все звонки человека в одну карточку и отсортировать карточки
 *    по последнему вызову, нужно прочитать журнал целиком. Постранично
 *    это невозможно в принципе: очередная страница может содержать
 *    старый звонок абонента, чья карточка уже показана выше.
 *
 * Поэтому здесь своя постраничность: страницы накапливаются в памяти,
 * а группировка каждый раз пересчитывается по всему накопленному набору.
 * Это дороже, чем Paging, но корректно — а группировка 2000 записей
 * на Default занимает единицы миллисекунд.
 *
 * ── Ограничение сверху ─────────────────────────────────────────────────────
 * У журнала за годы бывают десятки тысяч записей. Держать всё в памяти
 * незачем: до такой глубины прокрутки никто не доходит. Есть жёсткий
 * потолок, после которого предлагается воспользоваться поиском.
 */
class CallLogPager(
    private val pageSize: Int = DEFAULT_PAGE_SIZE,
    private val maxEntries: Int = MAX_ENTRIES
) {

    companion object {
        /**
         * Размер страницы. 150 записей — примерно пять экранов прокрутки:
         * пользователь не успевает долистать до конца, пока грузится
         * следующая порция, и подгрузка остаётся незаметной.
         */
        /**
         * ПЕРВАЯ СТРАНИЦА — 500 ЗАПИСЕЙ.
         *
         * ══════════════════════════════════════════════════════════════════
         * ПОЧЕМУ БОЛЬШЕ, ЧЕМ БЫЛО
         * ══════════════════════════════════════════════════════════════════
         * Со счётчиками в журнале страница должна была быть маленькой:
         * числа считались по загруженному и росли при каждой подгрузке.
         * Чем меньше страница, тем реже это заметно.
         *
         * Счётчиков больше нет — ограничение снято. Теперь размер
         * выбирается по другому признаку: сколько записей покрывает
         * обычную работу с журналом.
         *
         * 500 — это примерно полгода звонков у активного человека.
         * За ними лежит история, к которой возвращаются редко,
         * и её незачем читать при каждом открытии.
         *
         * ── Почему не всё сразу ────────────────────────────────────────────
         * На десяти тысячах записей чтение занимает секунды, и всё это
         * время экран пуст. 500 читаются за десятки миллисекунд.
         */
        const val DEFAULT_PAGE_SIZE = 500

        /**
         * Размер страницы при подгрузке.
         *
         * Меньше первой: подгрузка идёт при прокрутке, и человек в этот
         * момент смотрит на экран. Длинная пауза заметнее, чем при
         * открытии, когда он ещё не начал читать.
         */
        const val NEXT_PAGE_SIZE = 200

        /** Потолок накопления. Дальше — только поиск. */
        const val MAX_ENTRIES = 3000
    }

    /** Все загруженные записи, от новых к старым. */
    private val entries = mutableListOf<CallLogEntry>()

    /** Достигнут ли конец журнала. */
    var reachedEnd: Boolean = false
        private set

    /** Упёрлись ли в потолок накопления. */
    val reachedLimit: Boolean get() = entries.size >= maxEntries

    val loadedCount: Int get() = entries.size

    /** Смещение для следующего запроса к провайдеру. */
    val nextOffset: Int get() = entries.size

    /**
     * Сколько запрашивать в следующем запросе.
     *
     * Первая страница крупнее последующих: она читается при открытии,
     * когда человек ещё не смотрит на список. Подгрузка идёт при
     * прокрутке — там пауза заметнее, и порция меньше.
     */
    val nextLimit: Int
        get() {
            val size = if (entries.isEmpty()) pageSize else NEXT_PAGE_SIZE
            return minOf(size, maxEntries - entries.size).coerceAtLeast(0)
        }

    val canLoadMore: Boolean get() = !reachedEnd && !reachedLimit

    /**
     * Добавляет страницу.
     *
     * @return true, если что-то добавилось
     */
    fun append(page: List<CallLogEntry>): Boolean {
        if (page.isEmpty()) {
            reachedEnd = true
            return false
        }

        // Провайдер может вернуть записи, уже загруженные ранее: между
        // запросами журнал мог измениться, и смещение «съехало».
        // Дубли по id отсекаем, иначе счётчики в карточках удвоятся.
        val known = entries.mapTo(HashSet()) { it.id }
        val fresh = page.filter { it.id !in known }

        entries += fresh

        // Провайдер вернул меньше запрошенного — значит, это конец
        if (page.size < pageSize) reachedEnd = true

        return fresh.isNotEmpty()
    }

    /**
     * ЗАМЕНА ВСЕГО НАБОРА.
     *
     * Нужна при обновлении: перечитываем столько же записей, сколько
     * было загружено, и подменяем целиком. Смещение для следующей
     * подгрузки остаётся верным — оно считается от размера набора.
     *
     * Без этого любое обновление сбрасывало пейджер на первую страницу,
     * и прокрутка на 750 записей схлопывалась до 150.
     *
     * @param requested сколько записей запрашивали: если пришло меньше,
     *        значит достигнут конец журнала
     */
    fun replaceAll(newEntries: List<CallLogEntry>, requested: Int) {
        entries.clear()
        entries += newEntries
        reachedEnd = newEntries.size < requested
    }

    /** Полный сброс: при смене режима группировки. */
    fun reset() {
        entries.clear()
        reachedEnd = false
    }

    /**
     * Группировка по всему накопленному набору.
     *
     * Именно здесь решается проблема границ: группировщик видит все
     * записи разом, поэтому вызовы одного абонента на стыке страниц
     * склеиваются правильно.
     */
    /**
     * @param contactIdByNumber соответствие «номер → контакт» из книги.
     *        Без него человек с двумя номерами даёт две карточки:
     *        contactId в журнале часто пуст, и записи выглядят
     *        как разные абоненты
     */
    fun group(
        mode: CallLogGrouper.Mode,
        separateBySim: Boolean,
        contactIdByNumber: Map<String, Long> = emptyMap(),
        simLabelResolver: (String?) -> String?
    ): List<CallLogGroup> = CallLogGrouper.group(
        entries = entries.toList(),
        mode = mode,
        contactIdByNumber = contactIdByNumber,
        separateBySim = separateBySim,
        simLabelResolver = simLabelResolver
    )
}
