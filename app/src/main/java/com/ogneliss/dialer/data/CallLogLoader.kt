package com.ogneliss.dialer.data

import com.ogneliss.dialer.concurrency.suspendRunCatching

import com.ogneliss.dialer.log.Logger
import com.ogneliss.dialer.settings.GroupingMode

import com.ogneliss.dialer.di.DefaultDispatcher
import kotlinx.coroutines.launch
import kotlinx.coroutines.SupervisorJob
import kotlinx.coroutines.Job
import kotlinx.coroutines.CoroutineScope
import kotlinx.coroutines.CoroutineDispatcher
import kotlinx.coroutines.flow.first
import kotlinx.coroutines.withContext
import javax.inject.Inject
import javax.inject.Singleton

/**
 * ЗАГРУЗКА ЖУРНАЛА СТРАНИЦАМИ.
 *
 * ══════════════════════════════════════════════════════════════════════════
 * ЗАЧЕМ ВЫНЕСЕНО ИЗ VIEWMODEL
 * ══════════════════════════════════════════════════════════════════════════
 * Здесь три связанные вещи: пейджер, режим группировки и правило разделения
 * по SIM. Они всегда меняются вместе — режим группировки без перегруппировки
 * бессмыслен, а страница без группировки не пригодна для показа.
 *
 * Пока это лежало во ViewModel вперемешку с контактами, настройками
 * и правилами блокировки, связь не читалась: смена группировки
 * и перезагрузка страниц выглядели независимыми действиями, и одно
 * из них регулярно забывали.
 *
 * ── Что класс НЕ делает ────────────────────────────────────────────────────
 * Не хранит состояние интерфейса и не фильтрует. Фильтры применяются
 * поверх результата: они меняются чаще загрузки, и перечитывать журнал
 * при каждом нажатии чипа было бы расточительно.
 * ══════════════════════════════════════════════════════════════════════════
 */
@Singleton
class CallLogLoader @Inject constructor(
    private val repository: CallLogSource,
    private val simInfo: SimInfoSource,
    private val settings: GroupingSettings,
    /** Счётный диспетчер: группировка — работа процессора, не диска. */
    @DefaultDispatcher private val defaultDispatcher: CoroutineDispatcher
) {



    private val pager = CallLogPager()

    /** Есть ли что подгружать. */
    val canLoadMore: Boolean get() = pager.canLoadMore

    /**
     * Первая страница.
     *
     * Пейджер сбрасывается: режим группировки мог измениться, и накопленный
     * набор больше не соответствует тому, что нужно показать.
     */
    /**
     * ОБНОВЛЕНИЕ БЕЗ ПОТЕРИ ПРОКРУТКИ.
     *
     * ── Что было не так ────────────────────────────────────────────────────
     * Любое обновление сбрасывало пейджер и грузило только первую
     * страницу. В логе это видно так: человек прокрутил до offset=600,
     * вернулся в приложение — и следующая запись «offset=0».
     *
     * То есть 750 загруженных записей выбрасывались, список схлопывался
     * до 150, и всё приходилось подгружать заново прокруткой. Именно это
     * ощущается как «постоянная подгрузка и дёрганье».
     *
     * ── Как сейчас ─────────────────────────────────────────────────────────
     * При обновлении перечитывается столько же записей, сколько было
     * загружено. Прокрутка сохраняется, а новые звонки появляются сверху.
     */
    /**
     * Время последнего чтения журнала.
     *
     * Нужно, чтобы не перечитывать его при каждом обновлении настроек:
     * смена темы или языка пересоздаёт экран, а данные при этом
     * не менялись.
     */
    private var lastReadAt = 0L

    /**
     * СООТВЕТСТВИЕ «НОМЕР → КОНТАКТ».
     *
     * Строится по загруженной телефонной книге и нужен группировке:
     * без него человек с рабочим и личным номером даёт две карточки.
     *
     * Хранится здесь, а не передаётся в каждый вызов: группировка
     * происходит и при обновлении, и при подгрузке страницы, и при
     * смене режима — прокидывать карту через все пути значило бы
     * потерять её в одном из них.
     */
    private var contactIdByNumber: Map<String, Long> = emptyMap()

    /**
     * Итоги по номерам за всю историю.
     *
     * Читаются один раз при обновлении: полный проход по журналу
     * из двух столбцов дешевле, чем показывать растущие числа.
     */
    private var totals: Map<String, CallTotals> = emptyMap()

    /**
     * Подсчёт итогов в фоне.
     *
     * Отменяется при новом обновлении: считать дважды по одному
     * журналу незачем, а прежний проход всё равно устарел.
     */
    private var totalsJob: Job? = null

    /**
     * Область для фоновых задач загрузчика.
     *
     * SupervisorJob: сбой подсчёта итогов не должен отменять
     * остальное — журнал важнее статистики.
     */
    private val scope = CoroutineScope(SupervisorJob() + defaultDispatcher)

    /** Обновление соответствия при загрузке книги. */
    fun setContactNumbers(map: Map<String, Long>) {
        contactIdByNumber = map
    }

    private companion object {
        const val TAG = "CallLogLoader"

        /**
         * Через сколько после чтения имеет смысл читать снова.
         *
         * Журнал вызовов за секунду не меняется, а обновление
         * вызывается и там, где данные заведомо прежние: смена темы
         * или языка пересоздаёт экран и запускает полное чтение.
         *
         * В логе это выглядело как шесть чтений 450 записей подряд
         * при переключении темы.
         */
        const val MIN_REREAD_INTERVAL_MS = 1000L
    }

    /**
     * ЕСТЬ ЛИ СМЫСЛ ПЕРЕЧИТЫВАТЬ.
     *
     * ── Зачем ──────────────────────────────────────────────────────────────
     * В логе видно, как переключение темы шесть раз подряд вызывало
     * чтение 450 записей: каждое пересоздание экрана после смены
     * настройки запускало полное обновление.
     *
     * Журнал вызовов за две секунды не меняется. Пропускаем чтение,
     * если с прошлого прошло меньше секунды, — подписка на провайдер
     * всё равно сообщит о настоящем изменении.
     */
    private fun tooSoonToReread(): Boolean =
        System.currentTimeMillis() - lastReadAt < MIN_REREAD_INTERVAL_MS

    /**
     * @param force читать, не глядя на порог по времени.
     *
     * ── Зачем нужен обход ──────────────────────────────────────────────────
     * Порог в секунду защищает от пачки уведомлений провайдера, но
     * с действиями пользователя он сталкивается лоб в лоб: человек
     * открыл экран (чтение), тут же смахнул запись — и обновление
     * попадает в ту же секунду.
     *
     * Результат тот же, что был: удалённая запись остаётся на экране.
     * Порог должен сдерживать поток от системы, а не решения человека.
     */
    suspend fun refreshKeepingPosition(force: Boolean = false): List<CallLogGroup> {
        /*
         * Данные не менялись — только перегруппируем.
         *
         * Перегруппировка работает с уже загруженными записями
         * и стоит долей миллисекунды против чтения шестисот строк
         * из провайдера.
         */
        /*
         * Порог по времени — единственная защита от лишних чтений.
         *
         * ── Почему признака «данные изменились» больше нет ──────────────────
         * Он пропускал чтение, если провайдер не сообщал об изменении.
         * Но журнал меняет и само приложение — удаление записи,
         * блокировка, очистка, — и провайдер об этом молчит.
         *
         * Удалённая запись оставалась на экране, пока система
         * не пришлёт уведомление. Для человека это выглядело как
         * «удаление не работает».
         *
         * Теперь разделение по смыслу: refresh() читает всегда,
         * а для изменений вида есть regroup() — он к провайдеру
         * не обращается вовсе.
         *
         * Порог в секунду остаётся: подписка срабатывает несколько раз
         * на одно изменение — система дописывает длительность, имя
         * и фото по очереди.
         */
        if (!force && tooSoonToReread() && pager.loadedCount > 0) return group()

        val loaded = pager.loadedCount
        if (loaded <= CallLogPager.DEFAULT_PAGE_SIZE) return loadFirstPage()

        val page = suspendRunCatching {
            repository.loadEntries(limit = loaded, offset = 0)
        }.getOrElse {
            // Отмена — не ошибка: разбор у loadNextPage
            if (it is kotlinx.coroutines.CancellationException) throw it
            Logger.e(TAG, "Не удалось перечитать журнал", it)
            return group()
        }

        pager.replaceAll(page, requested = loaded)
        lastReadAt = System.currentTimeMillis()
        return group()
    }

    suspend fun loadFirstPage(): List<CallLogGroup> {
        lastReadAt = System.currentTimeMillis()
        pager.reset()

        /*
         * Итоги читаются вместе с первой страницей.
         *
         * Дальше они не меняются, пока не появится новый вызов —
         * а тогда обновление начнётся заново с первой страницы.
         *
         * Запрос из двух столбцов по всему журналу: десятки
         * миллисекунд даже на тысячах записей, потому что провайдер
         * не собирает имена, фотографии и подписи SIM.
         */
        /*
         * ИТОГИ СЧИТАЮТСЯ В ФОНЕ, А НЕ ПЕРЕД ПОКАЗОМ.
         *
         * ══════════════════════════════════════════════════════════════════
         * ПОЧЕМУ
         * ══════════════════════════════════════════════════════════════════
         * Счётчиков в журнале больше нет — они нужны только карточке
         * абонента, куда заходят отдельно и позже.
         *
         * Держать открытие журнала на полном проходе по истории ради
         * чисел, которых на экране не будет, значит платить задержкой
         * за то, чем не пользуются.
         *
         * Запускаем в фоне: к моменту, когда человек откроет карточку,
         * итоги уже посчитаны. Если не успели — карточка покажет числа
         * по загруженным записям, а следующее открытие будет точным.
         */
        totalsJob?.cancel()
        totalsJob = scope.launch {
            totals = suspendRunCatching { repository.totalsByNumber() }
                .onFailure { Logger.w(TAG, "Не удалось посчитать итоги журнала", it) }
                .getOrDefault(emptyMap())
        }

        val page = suspendRunCatching {
            repository.loadEntries(limit = CallLogPager.DEFAULT_PAGE_SIZE)
        }.getOrElse {
            // Отмена — не ошибка чтения: разбор у loadNextPage ниже
            if (it is kotlinx.coroutines.CancellationException) throw it
            Logger.e(TAG, "Не удалось прочитать первую страницу журнала", it)
            emptyList()
        }
        pager.append(page)
        return group()
    }

    /**
     * Следующая страница.
     *
     * @return обновлённый список или null, если добавить нечего —
     *         тогда вызывающему коду не нужно трогать состояние интерфейса
     */
    suspend fun loadNextPage(): List<CallLogGroup>? {
        if (!pager.canLoadMore) return null

        val page = suspendRunCatching {
            repository.loadEntries(limit = pager.nextLimit, offset = pager.nextOffset)
        }.getOrElse {
            /*
             * ══════════════════════════════════════════════════════════════
             * ОТМЕНА — НЕ ОШИБКА, И ЕЁ НЕЛЬЗЯ ГЛОТАТЬ
             * ══════════════════════════════════════════════════════════════
             * Найдено по журналу приложения: «Не удалось подгрузить страницу
             * журнала — y0 was cancelled». Это не сбой чтения. refresh()
             * отменяет предыдущее обновление, когда начинается новое, —
             * так и задумано, — и отмена прилетала сюда как исключение.
             *
             * runCatching ловит всё, в том числе отмену. Дальше было хуже,
             * чем лишняя строка в логе: вместо страницы возвращался пустой
             * список, а пустая страница для пейджера означает «журнал
             * кончился» (reachedEnd = true). После этого догрузка
             * прекращалась: журнал обрывался на уже загруженных записях,
             * пока что-нибудь не перечитает его с начала.
             *
             * Отмену пробрасываем дальше — корутина завершится, как должна,
             * а пейджер останется в прежнем состоянии.
             */
            if (it is kotlinx.coroutines.CancellationException) throw it
            Logger.e(TAG, "Не удалось подгрузить страницу журнала", it)
            emptyList()
        }

        return if (pager.append(page)) group() else null
    }

    /**
     * Перегруппировка накопленных записей.
     *
     * Вызывается при смене режима группировки: перечитывать журнал
     * для этого не нужно — записи уже в памяти, меняется лишь способ
     * их объединения.
     */
    suspend fun regroup(): List<CallLogGroup> = group()

    /**
     * ГРУППИРОВКА В ФОНОВОМ ПОТОКЕ.
     *
     * ── Почему это важно ───────────────────────────────────────────────────
     * Группировка перебирает все загруженные записи, сравнивает соседние,
     * склеивает карточки и сортирует результат. На трёх тысячах записей
     * это десятки миллисекунд.
     *
     * Вызывается она из viewModelScope, а его диспетчер по умолчанию —
     * ГЛАВНЫЙ ПОТОК. То есть вся эта работа выполнялась между кадрами
     * отрисовки: чтение из провайдера уходило в фон, а обработка
     * прочитанного оставалась на главном.
     *
     * Заметнее всего при подгрузке страницы во время прокрутки —
     * ровно в тот момент, когда плавность нужнее всего.
     */
    private suspend fun group(): List<CallLogGroup> = withContext(defaultDispatcher) {
        val mode = when (settings.groupingMode.first()) {
            GroupingMode.CONSECUTIVE -> CallLogGrouper.Mode.CONSECUTIVE
            GroupingMode.BY_CONTACT -> CallLogGrouper.Mode.BY_CONTACT
            GroupingMode.NONE -> CallLogGrouper.Mode.NONE
        }

        // Разделять карточки по SIM имеет смысл только когда карт
        // действительно несколько: иначе бейдж на каждой записи
        // не несёт информации и лишь занимает место
        val separateBySim = simInfo.availableSlots().size > 1

        val groups = pager.group(mode, separateBySim, contactIdByNumber) {
            simInfo.labelForAccount(it)
        }

        /*
         * ИТОГИ ПОДСТАВЛЯЮТСЯ ПОВЕРХ ПОСЧИТАННОГО ПО СТРАНИЦАМ.
         *
         * ══════════════════════════════════════════════════════════════════
         * ЗАЧЕМ
         * ══════════════════════════════════════════════════════════════════
         * Группировка считает вызовы по загруженным записям — иначе
         * и не может: страниц может быть ещё не всё. Но человеку она
         * показывает числа, которые растут при каждой подгрузке:
         * «5 вызовов» превращаются в «12», потом в «47».
         *
         * Здесь числа заменяются итоговыми — посчитанными один раз
         * по всему журналу лёгким запросом из двух столбцов.
         *
         * ── Что остаётся от группировки ────────────────────────────────────
         * Всё остальное: какие записи попали в карточку, последний
         * вызов, время, номера. Меняются только счётчики.
         *
         * ── Если итогов нет ────────────────────────────────────────────────
         * Запрос мог не пройти — нет разрешения, прошивка отказала.
         * Тогда остаются числа по страницам: неточные, но лучше нулей.
         */
        if (totals.isEmpty()) return@withContext groups

        groups.map { g ->
            val t = totals[g.e164] ?: return@map g

            g.copy(
                count = t.total,
                incomingCount = t.incoming,
                outgoingCount = t.outgoing,
                missedCount = t.missed,
                rejectedCount = t.rejected,
                totalDurationSec = t.durationSec
            )
        }
    }
}
