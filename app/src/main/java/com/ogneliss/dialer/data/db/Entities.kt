package com.ogneliss.dialer.data.db

import androidx.room.Entity
import androidx.room.Index
import androidx.room.PrimaryKey

/**
 * Заметка и метки к номеру. Ключ — E.164, чтобы запись переживала
 * удаление контакта и работала для номеров, которых нет в книге.
 */
@Entity(tableName = "number_notes")
data class NumberNoteEntity(
    @PrimaryKey val e164: String,
    val note: String = "",
    val tags: String = "",          // "спам,банк" — хранится строкой, парсится в UI
    val customLabel: String? = null, // как показывать номер вместо "Неизвестный"
    val updatedAt: Long = System.currentTimeMillis()
)

/** Списки блокировки и разрешений. Тип разделён, чтобы белый список имел приоритет. */
@Entity(tableName = "number_rules", indices = [Index("kind")])
data class NumberRuleEntity(
    @PrimaryKey val pattern: String,   // E.164 или маска: "+7800*"
    val kind: String,                  // "block" | "allow"
    val comment: String? = null,
    val createdAt: Long = System.currentTimeMillis()
)

/**
 * ЗАПОМНЕННЫЙ ВЫБОР SIM ДЛЯ АБОНЕНТА.
 *
 * Появилась в схеме версии 2.
 *
 * Зачем: при двух активных SIM пользователь обычно звонит конкретному
 * человеку всегда с одной и той же карты — рабочим коллегам с рабочей,
 * родным с личной. Спрашивать каждый раз утомительно, а глобальная
 * «SIM по умолчанию» не решает задачу.
 *
 * Ключ — E.164 номера. Для контакта с несколькими номерами предпочтение
 * хранится отдельно для каждого: рабочий и домашний номера одного человека
 * вполне могут требовать разных SIM.
 */
@Entity(tableName = "sim_preferences")
data class SimPreferenceEntity(
    @PrimaryKey val e164: String,
    /** Индекс слота SIM: 0 — первая, 1 — вторая. */
    val slotIndex: Int,
    val updatedAt: Long = System.currentTimeMillis()
)

/** Индекс T9: пересчитывается в фоне, чтобы поиск не сканировал контакты каждый раз. */
@Entity(tableName = "t9_index", indices = [Index("digits")])
data class T9IndexEntity(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val contactId: Long,
    val displayName: String,
    val number: String,
    val e164: String,
    val digits: String,        // имя, переведённое в цифры
    val numberDigits: String
)

/**
 * ЗАБЛОКИРОВАННЫЙ ВЫЗОВ.
 *
 * ══════════════════════════════════════════════════════════════════════════
 * ПОЧЕМУ В БАЗЕ, А НЕ В ПАМЯТИ
 * ══════════════════════════════════════════════════════════════════════════
 * Сначала причины хранились в памяти и терялись при перезапуске
 * процесса. Это было ошибкой: самый частый случай — человек утром
 * открывает телефон, видит пропущенные за ночь и хочет понять, почему
 * они не прошли. К этому моменту процесс давно перезапущен, и объяснять
 * уже нечем.
 *
 * ── Почему ключ — номер, а не составной ────────────────────────────────────
 * Нужна последняя причина по номеру: если правило сменилось, старая
 * запись только запутает. Номер как первичный ключ даёт замену
 * при повторе бесплатно.
 *
 * ── Про размер ─────────────────────────────────────────────────────────────
 * Старые записи чистятся по времени, а не по количеству: причина
 * блокировки годичной давности бесполезна, а пятисотая по счёту
 * за вчера — вполне нужна.
 */
@Entity(
    tableName = "blocked_calls",
    // Индекс по времени: выборка последних и очистка старых идут по нему.
    // Без индекса каждая означала бы перебор всей таблицы
    indices = [Index("at")]
)
data class BlockedCallEntity(
    @PrimaryKey val e164: String,
    /** Имя значения SpamPolicy.Reason. Строкой, чтобы пережить обфускацию. */
    val reason: String,
    /** BLOCKED или SILENCED: для звонящего это разные вещи. */
    val outcome: String,
    val at: Long = System.currentTimeMillis()
)

/**
 * КЭШ КОНТАКТА.
 *
 * ══════════════════════════════════════════════════════════════════════════
 * ЗАЧЕМ ДЕРЖАТЬ КОПИЮ ТЕЛЕФОННОЙ КНИГИ
 * ══════════════════════════════════════════════════════════════════════════
 * Чтение книги через провайдера занимает секунды: на большой книге
 * до десяти. Всё это время журнал показывается без фотографий,
 * а человек с несколькими номерами — несколькими карточками.
 *
 * Провайдер быстрее не станет: он собирает данные из нескольких таблиц
 * и нескольких аккаунтов. Единственный способ показать сведения сразу —
 * иметь их до того, как чтение началось.
 *
 * ── Что храним ─────────────────────────────────────────────────────────────
 * Только нужное журналу: имя, фотография, номера. Всё остальное —
 * адреса, дни рождения, заметки самой книги — читается на экране
 * контактов, где задержка терпима.
 *
 * ── Про устаревание ────────────────────────────────────────────────────────
 * Кэш заведомо отстаёт: контакт могли переименовать минуту назад.
 * Это допустимо — он показывается ровно до того, как придёт настоящее
 * чтение, и заменяется им.
 *
 * Хуже показать пустоту, чем показать вчерашнее имя.
 */
@Entity(tableName = "contact_cache")
data class ContactCacheEntity(
    @PrimaryKey val id: Long,
    val displayName: String,
    val photoUri: String?,
    val starred: Boolean,
    /** Номера через перевод строки: отдельная таблица здесь избыточна. */
    val numbers: String,
    /** Номера в E.164 в том же порядке — по ним идёт сопоставление. */
    val e164: String,
    /**
     * Имя «Фамилия Имя» (DISPLAY_NAME_ALTERNATIVE, 1.6.2) — для настройки
     * «Как показывать имя». Пусто — совпадает с displayName или ещё
     * не прочитано из книги. В кэше — чтобы при запуске журнал не
     * показывал секунду «Имя Фамилия», а потом не переставлял слова.
     */
    val nameAlt: String = ""
)

/**
 * ЗАПЛАНИРОВАННОЕ НАПОМИНАНИЕ ПЕРЕЗВОНИТЬ.
 *
 * ══════════════════════════════════════════════════════════════════════════
 * ЗАЧЕМ ХРАНИТЬ ТО, ЧТО И ТАК СТОИТ В БУДИЛЬНИКЕ
 * ══════════════════════════════════════════════════════════════════════════
 * До этой таблицы напоминание существовало только как будильник
 * в AlarmManager. Из этого следовало три беды, и все три человек
 * замечал не сразу:
 *
 * • нельзя было посмотреть, что назначено. Поставил «через два часа»
 *   и забыл — проверить нечем;
 * • нельзя было отменить, не дожидаясь срабатывания;
 * • после перезагрузки телефона будильники пропадают, и восстановить
 *   их было не из чего. Напоминание молча исчезало.
 *
 * Ключ — номер в E.164: на один номер одно напоминание. Второе
 * заменяет первое, и это правильно: «напомни через час», сказанное
 * дважды, означает «через час от последнего раза», а не два звонка.
 */
@Entity(tableName = "callback_reminders")
data class ReminderEntity(
    @PrimaryKey val e164: String,
    /** Имя на момент постановки: контакт могли удалить, а напоминание осталось. */
    val displayName: String?,
    /** Когда сработает, RTC. */
    val atMillis: Long,
    val createdAt: Long
)

/**
 * ОТМЕТКА «СПАМ» ИЛИ «МОШЕННИКИ».
 *
 * Появилась в схеме версии 6.
 *
 * ══════════════════════════════════════════════════════════════════════════
 * ПОЧЕМУ ОТДЕЛЬНО ОТ ЗАМЕТОК
 * ══════════════════════════════════════════════════════════════════════════
 * До версии 6 отметка была меткой внутри заметки — строкой «spam»
 * в поле tags. Это сцепляло две разные вещи:
 *
 * • заметка — то, что человек написал себе («замер мебели»);
 *   она живёт по сроку хранения и может быть удалена целиком;
 * • отметка — решение о номере: блокировать или предупреждать.
 *   Удалить заметку и тем самым молча снять отметку о мошенниках —
 *   ошибка, которую срок хранения избегал только потому, что про это
 *   вспомнили (NotesRetention.PROTECTED_TAGS).
 *
 * Вдобавок в будущем отметку, возможно, придётся отправлять в общую
 * базу (docs/SPAM_SERVER_DESIGN.md), а заметку — никогда. Хранить
 * их вместе значило бы каждый раз вспоминать, что из записи можно
 * показать серверу.
 *
 * ── Одна отметка на номер ──────────────────────────────────────────────────
 * Не набор меток, а одна: номер либо спам, либо мошенники, либо ничего.
 * Если было и то и другое, при переносе остаются мошенники — обвинение
 * тяжелее, и именно оно должно быть видно.
 */
@Entity(tableName = "spam_marks")
data class SpamMarkEntity(
    @PrimaryKey val e164: String,
    /** "spam" | "fraud" — ключи, а не переводы: смена языка не ломает отметку. */
    val type: String,
    /** Когда отмечен, RTC. Нужен будущей общей базе и сроку давности. */
    val markedAt: Long
)

