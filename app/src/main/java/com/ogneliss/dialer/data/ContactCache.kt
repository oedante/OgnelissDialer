package com.ogneliss.dialer.data

import com.ogneliss.dialer.concurrency.suspendRunCatching

import com.ogneliss.dialer.data.db.ContactCacheDao
import com.ogneliss.dialer.data.db.ContactCacheEntity
import com.ogneliss.dialer.log.Logger
import javax.inject.Inject
import javax.inject.Singleton

/**
 * КЭШ ТЕЛЕФОННОЙ КНИГИ.
 *
 * ══════════════════════════════════════════════════════════════════════════
 * ЗАЧЕМ ОН НУЖЕН
 * ══════════════════════════════════════════════════════════════════════════
 * Чтение книги через провайдера занимает секунды — на большой книге
 * до десяти. Всё это время журнал показывался без фотографий,
 * а человек с несколькими номерами выглядел несколькими карточками.
 *
 * Провайдер быстрее не станет: он собирает данные из нескольких таблиц
 * и нескольких аккаунтов. Единственный способ показать сведения сразу —
 * иметь их ДО того, как чтение началось.
 *
 * ── Порядок работы ─────────────────────────────────────────────────────────
 * 1. При запуске читаем кэш — это одна выборка из локальной базы,
 *    десятки миллисекунд.
 * 2. Показываем журнал с фотографиями и правильной группировкой.
 * 3. Параллельно читаем провайдер и заменяем данные настоящими.
 *
 * Человек видит верную картину сразу, а расхождение — если контакт
 * переименовали минуту назад — держится доли секунды.
 *
 * ── Почему устаревание допустимо ───────────────────────────────────────────
 * Кэш заведомо отстаёт. Но выбор здесь не между «свежим» и «старым»,
 * а между «старым сейчас» и «никаким десять секунд».
 *
 * Показать вчерашнее имя лучше, чем пустой круг: имя почти наверняка
 * то же, а пустота выглядит поломкой.
 */
@Singleton
class ContactCache @Inject constructor(
    private val dao: ContactCacheDao
) {

    /**
     * Контакты из кэша.
     *
     * Пустой список означает первый запуск: кэша ещё нет, и придётся
     * дождаться провайдера. Дальше он будет всегда.
     */
    suspend fun load(): List<Contact> = runCatching {
        /*
         * ЗАЩИТА ОТ ДУБЛЕЙ ПРИ ЧТЕНИИ.
         *
         * ══════════════════════════════════════════════════════════════════
         * ОТКУДА ОНИ БЕРУТСЯ
         * ══════════════════════════════════════════════════════════════════
         * Кэш хранит контакты по идентификатору, и повторов там быть
         * не должно. Но идентификатор в телефонной книге не вечен:
         * при синхронизации аккаунта система может пересоздать запись
         * с новым номером — старая остаётся в кэше до следующей
         * перезаписи.
         *
         * В журнале это выглядело как два одинаковых имени подряд,
         * причём у одного из них не было фотографии: у устаревшей
         * записи путь к снимку уже не открывается.
         *
         * ── Почему по имени и номеру, а не по идентификатору ────────────────
         * Идентификатор у дублей как раз разный — по нему они
         * не схлопнутся. Человек же считает одинаковыми записи
         * с одним именем и одним номером, и это верный признак.
         *
         * ── Почему остаётся тот, у кого есть фото ──────────────────────────
         * Из двух записей об одном человеке полезнее та, что покажет
         * лицо. Пустая ничего не добавляет.
         */
        /*
         * ПОРЯДОК СПИСКА СОХРАНЯЕТСЯ.
         *
         * ── Что было не так ────────────────────────────────────────────────
         * Здесь стояло .sortedByDescending { photoUri != null } прямо
         * перед distinctBy — то есть весь список переупорядочивался
         * ради выбора победителя среди дублей.
         *
         * Запрос в ContactCacheDao отдаёт контакты по алфавиту, а после
         * такой сортировки они шли иначе: сначала все с фотографиями,
         * потом все без. Экран контактов группирует по первой букве,
         * но ВНУТРИ буквы показывает список как есть — и первые секунды
         * после запуска, пока не пришло чтение провайдера, «Анна»
         * оказывалась ниже «Антона» только потому, что у неё нет снимка.
         *
         * ── Как теперь ─────────────────────────────────────────────────────
         * Сортировка нужна только чтобы выбрать, какая из двух записей
         * останется. Поэтому победители вычисляются отдельно, а список
         * возвращается в исходном порядке.
         */
        val rows = dao.all()
        val winners = rows
            .sortedByDescending { it.photoUri != null }
            .distinctBy { it.displayName to it.e164 }
            .mapTo(HashSet()) { it.id }

        rows.filter { it.id in winners }
            .map { row ->
            val numbers = row.numbers.split('\n')
            val e164s = row.e164.split('\n')

            Contact(
                id = row.id,
                lookupKey = "",
                displayName = row.displayName,
                photoUri = row.photoUri,
                starred = row.starred,
                numbers = numbers.mapIndexed { i, value ->
                    PhoneNumber(
                        value = value,
                        label = "",
                        // Длина списков совпадает, но полагаться на это
                        // нельзя: строка могла испортиться при сбое записи
                        e164 = e164s.getOrElse(i) { value }
                    )
                }
            )
        }
    }.getOrElse {
        Logger.w(TAG, "Не удалось прочитать кэш контактов", it)
        emptyList()
    }

    /**
     * Обновление кэша после чтения провайдера.
     *
     * Вызывается всегда, когда книга прочитана успешно — даже если она
     * не изменилась: сравнивать дороже, чем перезаписать сотню строк.
     */
    suspend fun save(contacts: List<Contact>) {
        if (contacts.isEmpty()) return

        suspendRunCatching {
            dao.replaceAll(
                /*
                 * Дубли отсеиваются и при записи.
                 *
                 * Иначе они вернутся в кэш при следующем чтении книги,
                 * и защита при загрузке будет вычищать их снова
                 * и снова — работа впустую на каждом запуске.
                 *
                 * Признак тот же: одно имя и один номер.
                 */
                contacts
                    .sortedByDescending { it.photoUri != null }
                    .distinctBy { it.displayName to it.numbers.firstOrNull()?.e164 }
                    .map { contact ->
                    ContactCacheEntity(
                        id = contact.id,
                        displayName = contact.displayName,
                        photoUri = contact.photoUri,
                        starred = contact.starred,
                        numbers = contact.numbers.joinToString("\n") { it.value },
                        e164 = contact.numbers.joinToString("\n") { it.e164 }
                    )
                }
            )
        }.onFailure { Logger.w(TAG, "Не удалось сохранить кэш контактов", it) }
    }

    private companion object {
        const val TAG = "ContactCache"
    }
}
