package com.ogneliss.dialer.data

import androidx.compose.runtime.Immutable

/**
 * РЕШЕНИЕ О КНОПКАХ ВЫЗОВА ПО СОСТАВУ SIM.
 *
 * Чистая логика без Android — покрыта тестами. Проверить это вручную
 * означало бы иметь под рукой телефоны со всеми сочетаниями карт.
 *
 * ── Почему «две SIM» — не одно состояние, а несколько ───────────────────────
 * Наивная проверка «карт больше одной → две кнопки» ошибается в трёх
 * реальных случаях:
 *
 * 1. ДВА СЛОТА, ОДНА КАРТА. Слот есть, карты нет. Система такой
 *    подписки не отдаёт, но полагаться на это нельзя: часть прошивок
 *    возвращает запись с пустым номером.
 *
 * 2. КАРТА ОТКЛЮЧЕНА В НАСТРОЙКАХ. Пользователь выключил вторую SIM,
 *    не вынимая её. Звонить с неё нельзя.
 *
 * 3. КАРТА ТОЛЬКО ДЛЯ ИНТЕРНЕТА. Тарифы для данных и eSIM-профили
 *    операторов часто не поддерживают голос. Карта активна, в списке
 *    есть — но кнопка вызова с неё привела бы к ошибке соединения,
 *    и пользователь не понял бы, почему звонок не идёт.
 *
 * Отсюда правило: кнопка показывается только для карты, у которой есть
 * СООТВЕТСТВУЮЩИЙ ГОЛОСОВОЙ АККАУНТ в телефонии.
 */
object SimCallPlan {

    /** Как показывать кнопки вызова. */
    sealed interface Layout {
        /**
         * Одна кнопка без указания карты.
         *
         * Так выглядит и телефон с одной SIM, и случай, когда список карт
         * недоступен — например, не выдано разрешение. Выбор карты
         * в этом случае делает система, и это правильное поведение:
         * лучше позвонить с картой по умолчанию, чем не позвонить вовсе.
         */
        data object Single : Layout

        /** Кнопка на каждую голосовую карту. */
        /** @Immutable: раскладка кнопок вызова читается при каждой отрисовке. */
        @Immutable
        data class PerSim(val sims: List<SimSlot>) : Layout
    }

    /**
     * Максимум кнопок в ряд. Больше двух не помещается по ширине:
     * при трёх картах (физическая плюс два eSIM-профиля) кнопки стали бы
     * уже 100 dp, а это ниже комфортного порога для главного действия.
     * В таком случае показываем одну кнопку и спрашиваем карту отдельно.
     */
    const val MAX_INLINE_BUTTONS = 2

    /**
     * @param sims активные карты
     * @param voiceCapableSubscriptionIds идентификаторы подписок,
     *        у которых есть голосовой аккаунт в телефонии
     */
    fun decide(
        sims: List<SimSlot>,
        voiceCapableSubscriptionIds: Set<Int>
    ): Layout {
        // Карты без голосового аккаунта отсеиваются: звонок с такой
        // просто не пройдёт, а кнопка обещала бы обратное
        val callable = sims.filter { it.subscriptionId in voiceCapableSubscriptionIds }

        return when {
            callable.size <= 1 -> Layout.Single
            callable.size <= MAX_INLINE_BUTTONS -> Layout.PerSim(callable)
            // Три и больше: в ряд не помещаются, спрашиваем отдельно
            else -> Layout.Single
        }
    }

    /**
     * Нужно ли спрашивать карту отдельным диалогом.
     * Верно, когда голосовых карт больше, чем помещается кнопок.
     */
    fun requiresSimPicker(
        sims: List<SimSlot>,
        voiceCapableSubscriptionIds: Set<Int>
    ): Boolean =
        sims.count { it.subscriptionId in voiceCapableSubscriptionIds } > MAX_INLINE_BUTTONS

    /** Голосовые карты — для фильтров и статистики. */
    fun callableSims(
        sims: List<SimSlot>,
        voiceCapableSubscriptionIds: Set<Int>
    ): List<SimSlot> = sims.filter { it.subscriptionId in voiceCapableSubscriptionIds }
}
