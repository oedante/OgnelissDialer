package com.ogneliss.dialer.data

/**
 * ЗАМЕТКА КАК ЗАМЕНА ИМЕНИ.
 *
 * ══════════════════════════════════════════════════════════════════════════
 * ЗАЧЕМ ЭТО НУЖНО
 * ══════════════════════════════════════════════════════════════════════════
 * Большинство входящих — от людей, которых не хочется добавлять в книгу:
 * курьер, мастер, оператор, разовый клиент. Заводить контакт ради одного
 * звонка никто не станет, и через неделю номер снова становится
 * неизвестным.
 *
 * Заметка закрывает этот пробел: «доставка мебели» рядом с номером
 * отвечает на вопрос «кто это» без засорения телефонной книги.
 *
 * ── Три случая ─────────────────────────────────────────────────────────────
 *
 * 1. ЕСТЬ ИМЯ. Заголовок — имя, заметка идёт второй строкой как
 *    уточнение: «Андрей Клинов» / «сосед сверху».
 *
 * 2. ИМЕНИ НЕТ, ЕСТЬ ЗАМЕТКА. Заголовок — заметка, номер под ней.
 *    Именно это и есть основной сценарий: человек видит «доставка мебели»
 *    вместо безликого «+7 900…».
 *
 * 3. НЕТ НИЧЕГО. Заголовок — номер. Пустая строка выглядит как сбой.
 *
 * ── Про длину ──────────────────────────────────────────────────────────────
 * Заметки бывают разными: «курьер» и «никогда не брать трубку,
 * мошенники». Первая помещается целиком, вторая — нет.
 *
 * Обрезка идёт по границе слова, а не по символу: «никогда не брать…»
 * читается, а «никогда не бр…» выглядит как ошибка. Ключевое слово
 * почти всегда в начале — заметки пишут, начиная с главного.
 * ══════════════════════════════════════════════════════════════════════════
 */
object NoteDisplay {

    /**
     * Предел заголовка. Примерно столько помещается в одну строку
     * карточки на телефоне средней ширины при обычном размере шрифта.
     */
    const val TITLE_LIMIT = 32

    /** Предел второй строки: она мельче, помещается больше. */
    const val SUBTITLE_LIMIT = 48

    /** Что показать в строке списка. */
    data class Result(
        val title: String,
        val subtitle: String?,
        /** Заголовок взят из заметки — интерфейс может пометить это иначе. */
        val titleFromNote: Boolean
    )

    /**
     * @param displayName имя из контактов, если есть
     * @param note текст заметки пользователя
     * @param formattedNumber отформатированный номер — запасной вариант
     */
    fun resolve(
        displayName: String?,
        note: String?,
        formattedNumber: String
    ): Result {
        val cleanName = displayName?.trim()?.takeIf { it.isNotEmpty() }
        val cleanNote = note?.trim()?.takeIf { it.isNotEmpty() }

        return when {
            // Имя есть: заметка уточняет, но не подменяет
            cleanName != null -> Result(
                title = cleanName,
                subtitle = cleanNote?.let { truncate(it, SUBTITLE_LIMIT) },
                titleFromNote = false
            )

            // Имени нет, но есть заметка — ради этого случая всё и делалось
            cleanNote != null -> Result(
                title = truncate(cleanNote, TITLE_LIMIT),
                subtitle = formattedNumber,
                titleFromNote = true
            )

            // Ничего нет: номер лучше пустоты
            else -> Result(
                title = formattedNumber,
                subtitle = null,
                titleFromNote = false
            )
        }
    }

    /**
     * Обрезка по границе слова.
     *
     * Посимвольная обрезка даёт «никогда не бр…», что читается как
     * опечатка. По слову получается «никогда не брать…» — понятно,
     * что текст продолжается.
     *
     * Если первое слово само длиннее предела, обрезаем посимвольно:
     * иначе вернулась бы пустая строка.
     */
    fun truncate(text: String, limit: Int): String {
        val single = text.replace('\n', ' ').replace(Regex("\\s+"), " ").trim()
        if (single.length <= limit) return single

        val cut = single.take(limit)
        val lastSpace = cut.lastIndexOf(' ')

        return if (lastSpace > limit / 2) {
            cut.take(lastSpace).trimEnd(',', '.', ';', ' ') + "…"
        } else {
            cut.trimEnd() + "…"
        }
    }

    /**
     * ИМЯ, ЗАМЕТКА И НОМЕР ДЛЯ ЭКРАНА ВЫЗОВА.
     *
     * Правила те же, что в журнале, но заметка обрезается позже:
     * экран вызова пустой, места хватает, а сведения нужнее всего
     * именно в этот момент — человек решает, брать трубку или нет.
     *
     * В списке журнала длинная заметка ломала бы высоту строк,
     * здесь этой заботы нет.
     */
    fun forCallScreen(
        displayName: String?,
        note: String?,
        formattedNumber: String
    ): Result {
        val base = resolve(displayName, note, formattedNumber)

        // Заметка целиком: обрезаем только совсем длинную
        val fullNote = note?.trim()?.takeIf { it.isNotEmpty() }
            ?.let { truncate(it, CALL_SCREEN_LIMIT) }

        return when {
            // Заметка стоит заголовком — она уже обрезана по своему пределу
            base.titleFromNote -> base

            // Имя есть: подставляем более длинный вариант заметки
            fullNote != null -> base.copy(subtitle = fullNote)

            else -> base
        }
    }

    /**
     * Предел длины заметки на экране вызова.
     *
     * Вчетверо больше, чем в списке: там длинная заметка ломала бы
     * высоту строк, здесь экран пустой.
     */
    private const val CALL_SCREEN_LIMIT = 120
}
