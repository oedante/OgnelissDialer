package com.ogneliss.dialer.settings

/**
 * ПАРАМЕТРЫ ЖЕСТА СВАЙПА.
 *
 * ══════════════════════════════════════════════════════════════════════════
 * ЗАЧЕМ ВЫНОСИТЬ ЭТО В НАСТРОЙКИ
 * ══════════════════════════════════════════════════════════════════════════
 * Подобрать пороги «на глаз» невозможно: они зависят от размера телефона,
 * от того, держат его одной рукой или двумя, от скорости движений
 * конкретного человека. То, что для одного «срабатывает слишком легко»,
 * для другого «приходится тянуть через весь экран».
 *
 * Значения по умолчанию подобраны так, чтобы жест не срабатывал случайно
 * при обычной прокрутке. Но это компромисс, и возможность его сдвинуть
 * стоит дешевле, чем спор о том, чей вариант правильный.
 *
 * ── Все значения в одном месте ─────────────────────────────────────────────
 * Раньше пороги были константами внутри SwipeRevealRow. При изменении
 * приходилось править код в трёх местах, и однажды две правки из трёх
 * не применились — свайп остался чутким, хотя в дорожной карте
 * значилось иначе.
 *
 * Теперь источник один, и рассинхронизация невозможна.
 * ══════════════════════════════════════════════════════════════════════════
 */
data class SwipeTuning(

    /**
     * Расстояние до срабатывания прямого действия, dp.
     *
     * Насколько нужно протянуть строку, чтобы действие выполнилось.
     * Меньше — быстрее, но случайные срабатывания при прокрутке;
     * больше — надёжнее, но утомительнее.
     */
    val triggerDistanceDp: Int = DEFAULT_TRIGGER_DP,

    /**
     * Доля пути до «защёлкивания» панели, проценты.
     *
     * После этой доли строка сама доезжает до конца. Малое значение
     * при быстром движении срабатывает почти мгновенно, и жест
     * ощущается неуправляемым.
     */
    val positionalThresholdPercent: Int = DEFAULT_POSITIONAL_PERCENT,

    /**
     * Скорость «броска», dp в секунду.
     *
     * При такой скорости жест срабатывает, не доходя до порога
     * расстояния. Низкое значение ловит обычную прокрутку, если палец
     * идёт под небольшим углом к вертикали — а он почти всегда идёт
     * под углом.
     */
    val velocityDpPerSecond: Int = DEFAULT_VELOCITY_DP,

    /**
     * Требовать ли, чтобы жест начинался горизонтально.
     *
     * При включении вертикальное движение отдаётся списку сразу,
     * и свайп не перехватывает прокрутку. Помогает тем, у кого палец
     * при листании идёт по дуге.
     */
    val requireHorizontalStart: Boolean = DEFAULT_REQUIRE_HORIZONTAL
) {

    companion object {
        /**
         * Значения по умолчанию.
         *
         * 140 dp — примерно треть ширины телефона: столько случайно
         * не проводят, но и намеренно тянуть не утомительно.
         *
         * 75 % требует довести движение почти до конца, зато результат
         * предсказуем.
         *
         * 450 dp/с — скорость осознанного броска вбок, обычная прокрутка
         * такой горизонтальной составляющей не даёт.
         */
        const val DEFAULT_TRIGGER_DP = 140
        const val DEFAULT_POSITIONAL_PERCENT = 75
        const val DEFAULT_VELOCITY_DP = 450
        const val DEFAULT_REQUIRE_HORIZONTAL = true

        /** Границы ползунков. */
        val TRIGGER_RANGE = 60..240
        val POSITIONAL_RANGE = 30..95
        val VELOCITY_RANGE = 150..900

        val DEFAULT = SwipeTuning()
    }

    /** Доля пути в виде множителя — в таком виде её ждёт компонент. */
    val positionalThreshold: Float get() = positionalThresholdPercent / 100f

    /** Отличается ли настройка от заводской. Для кнопки сброса. */
    val isDefault: Boolean get() = this == DEFAULT
}
