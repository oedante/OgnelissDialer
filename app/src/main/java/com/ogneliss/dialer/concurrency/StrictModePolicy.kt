package com.ogneliss.dialer.concurrency

import android.os.Build
import android.os.StrictMode
import com.ogneliss.dialer.BuildConfig
import com.ogneliss.dialer.log.Logger

/**
 * КОНТРОЛЬ НАРУШЕНИЙ В ГЛАВНОМ ПОТОКЕ.
 *
 * Назначение: во время разработки ловить операции, которые не должны
 * выполняться в главном потоке — чтение диска, обращение к сети,
 * утечки курсоров и незакрытые объекты.
 *
 * ── Почему это важно именно для диалера ────────────────────────────────────
 * Приложение постоянно работает с ContentProvider: журнал, контакты,
 * список блокировки. Забыть withContext(io) в одном месте легко,
 * а проявится это не сразу: на устройстве разработчика с пустым журналом
 * запрос отработает за миллисекунду. У пользователя с пятью тысячами
 * записей тот же код даст видимое подвисание.
 *
 * StrictMode превращает такую ошибку из «когда-нибудь заметим по отзывам»
 * в «падает прямо сейчас на моём столе».
 *
 * ── Только в debug ─────────────────────────────────────────────────────────
 * В release политика не включается: penaltyDeath уронил бы приложение
 * у пользователя из-за мелкого нарушения, которое он бы и не заметил.
 */
object StrictModePolicy {

    fun install() {
        if (!BuildConfig.DEBUG) return

        StrictMode.setThreadPolicy(
            StrictMode.ThreadPolicy.Builder()
                /*
                 * detectDiskReads НЕ включаем.
                 *
                 * ── Почему ─────────────────────────────────────────────
                 * Он перехватывает КАЖДОЕ чтение с диска, включая чтение
                 * ресурсов, шрифтов и растровых изображений при отрисовке.
                 * При прокрутке списка это десятки срабатываний в секунду,
                 * и каждое требует построения стека вызовов.
                 *
                 * Проверка выполняется в главном потоке и сама становится
                 * источником рывков — тех самых, ради поиска которых её
                 * и включали. Отладочный инструмент искажал то, что мерил.
                 *
                 * Записи ловим: они реже и опаснее — запись в главном
                 * потоке блокирует надолго.
                 */
                .detectDiskWrites()
                .detectNetwork()
                .detectCustomSlowCalls()
                .penaltyLog()
                /*
                 * penaltyFlashScreen убран.
                 *
                 * Вспышка на весь экран — работа с отрисовкой поверх
                 * той, что уже идёт. При частых срабатываниях экран
                 * мерцал, и это читалось как подтормаживание.
                 *
                 * Записи в лог достаточно: нарушения разбирают потом,
                 * а не ловят глазами в момент прокрутки.
                 */
                .build()
        )

        StrictMode.setVmPolicy(
            StrictMode.VmPolicy.Builder()
                .detectLeakedSqlLiteObjects()
                .detectLeakedClosableObjects()   // незакрытые курсоры
                .detectActivityLeaks()
                .apply {
                    if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.S) {
                        detectUnsafeIntentLaunch()
                    }
                }
                .penaltyLog()
                .build()
        )

        Logger.i("StrictMode", "Контроль главного потока включён (debug-сборка)")
    }
}
