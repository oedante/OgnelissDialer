package com.ogneliss.dialer.background

import android.content.Context
import com.ogneliss.dialer.log.Logger

/**
 * ЗАБЛОКИРОВАННЫЙ ЗВОНОК — БЕЗ УВЕДОМЛЕНИЯ (2.1.0).
 *
 * ══════════════════════════════════════════════════════════════════════════
 * БЫЛО
 * ══════════════════════════════════════════════════════════════════════════
 * О каждой блокировке приходило тихое уведомление «Вызов заблокирован»
 * с кнопкой «Разблокировать» (у номера со своим правилом) — чтобы ошибку
 * блокировки (школа, курьер, поликлиника) было видно сразу.
 *
 * ══════════════════════════════════════════════════════════════════════════
 * СТАЛО
 * ══════════════════════════════════════════════════════════════════════════
 * Правило автора 07.11.2026: человеку сообщается только критичное,
 * что может исправить лишь он. Заблокированный вызов — не такой случай:
 * блокировку он включил сам, а журнал и так отмечает каждый отсечённый
 * вызов (BlockedCallLog, «Заблокирован — …» в строке), и снять правило
 * можно из карточки или списков блокировки. Уведомление на каждый
 * вызов настойчивого робота только засоряло шторку.
 *
 * Отдельной настройки у уведомления не было — снимать нечего. Приёмник
 * кнопки «Разблокировать» убран вместе с уведомлением (и из манифеста).
 *
 * show() остаётся, пока его вызывает служба фильтрации
 * (call/OgnelissCallScreeningService) — её файлы в 2.1.0 правятся
 * параллельно; теперь это только строка в журнал разработчика. Вызов
 * там можно убрать вместе с этим файлом, а с ним — канал «Заблокированные
 * вызовы» (CallNotifications.CHANNEL_BLOCKED).
 */
object BlockedCallNotice {

    private const val TAG = "BlockedCallNotice"

    /**
     * @param hasOwnRule есть ли у номера собственное правило (не маска) —
     *   только для журнала разработчика.
     */
    @Suppress("UNUSED_PARAMETER")
    fun show(context: Context, e164: String, hasOwnRule: Boolean) {
        Logger.i(TAG, "Вызов заблокирован${if (hasOwnRule) " (своё правило)" else ""}: ${Logger.mask(e164)}")
    }
}
