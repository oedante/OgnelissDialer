package com.ogneliss.dialer.sms

/**
 * ТЕКСТ SMS В УВЕДОМЛЕНИЯХ (2.9.12; было — переключатель «Скрывать текст в уведомлениях», 2.9.1).
 *
 * Форум, eXense, 2.9.1: «прятать текст SMS из всплывающих уведомлений… коды подтверждения могут
 * попасть не на те глаза». И 26.11.2026: «пишет „Новое сообщение“, но если развернуть всплывающее
 * уведомление — тоже „Новое сообщение“; ожидалось, что хоть развернуть можно будет текст».
 *
 * Свёрнутое и раскрытое уведомление «разговором» (MessagingStyle) показывают одно и то же:
 * спрятать текст в свёрнутом и открыть в раскрытом Android не даёт. Поэтому три варианта:
 *  - [SHOW] — как всегда: уведомление-разговор с текстом;
 *  - [UNTIL_EXPANDED] — свёрнутое и всплывающее — «Новое сообщение», раскрытое — текст.
 *    Это обычное уведомление с длинным текстом (BigTextStyle), не «разговор»: в разделе
 *    «Разговоры» шторки его нет — цена того, что свёрнутый вид отличается от раскрытого;
 *  - [HIDE] — текста нет и в раскрытом (как переключатель 2.9.1).
 *
 * Включённый переключатель 2.9.1 читается как [HIDE]: кто прятал текст от чужих глаз, не должен
 * после обновления увидеть его в шторке без своего решения.
 */
enum class SmsTextMode {
    SHOW,
    UNTIL_EXPANDED,
    HIDE;

    companion object {
        /** null — значения нет (не выбирали): тогда решает прежний переключатель. */
        fun parse(name: String?): SmsTextMode? = entries.firstOrNull { it.name == name }

        /** Выбор или, если его нет, прежний переключатель «Скрывать текст» (2.9.1). */
        fun resolve(name: String?, legacyHide: Boolean?): SmsTextMode =
            parse(name) ?: if (legacyHide == true) HIDE else SHOW
    }
}
