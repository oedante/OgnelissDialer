package com.ogneliss.dialer.ui.theme

import androidx.compose.ui.unit.dp

/**
 * РАЗМЕРЫ ЭЛЕМЕНТОВ.
 *
 * Собраны в одном месте, чтобы режим «крупные кнопки» переключался
 * централизованно, а не правкой каждого экрана.
 *
 * MIN_TOUCH_TARGET = 48.dp — не пожелание дизайнера, а требование
 * Material Design и рекомендаций по доступности. Всё, что нажимается,
 * должно быть не меньше. Для экрана активного вызова взят запас 56 dp:
 * туда нажимают не глядя, часто одной рукой.
 */
object Dimens {
    val MIN_TOUCH_TARGET = 48.dp

    /**
     * ВЫСОТА КЛАВИШИ НАБОРА.
     *
     * ── Почему 60, а не 72 ─────────────────────────────────────────────────
     * Клавиатура занимает нижнюю половину экрана, и каждые 12 dp высоты
     * клавиши — это 48 dp списка вызовов, то есть ещё одна видимая
     * запись при открытой клавиатуре. А смотрят на список чаще,
     * чем набирают вручную.
     *
     * 60 dp — это 48 dp обязательного размера нажатия плюс запас
     * на промах. Ниже опускаться нельзя: 48 — требование доступности,
     * а не пожелание.
     *
     * Кому нужны крупные клавиши, включают «Большие кнопки» —
     * там 92 dp, и они не тронуты.
     */
    val dialKeyHeight = 60.dp
    val dialKeyHeightLarge = 92.dp

    val callButtonHeight = 56.dp
    val callButtonHeightLarge = 72.dp

    val avatarSize = 48.dp
    val avatarSizeLarge = 60.dp

    /**
     * Ширина одной кнопки в раскрывающейся панели свайпа.
     * 76 dp — компромисс: меньше не помещается подпись «…05-12»,
     * больше — три кнопки закрывают почти весь экран и непонятно,
     * по какой строке идёт свайп.
     */
    val swipeActionWidth = 76.dp
}
