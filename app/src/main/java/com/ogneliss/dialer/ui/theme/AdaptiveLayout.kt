package com.ogneliss.dialer.ui.theme

/**
 * ВЫБОР РАСКЛАДКИ ПОД РАЗМЕР ЭКРАНА.
 *
 * Назначение: решить, как расположить журнал и клавиатуру.
 * Чистая логика без Compose — покрыта тестами.
 *
 * ── Почему для диалера это не косметика ────────────────────────────────────
 * Клавиатура занимает половину экрана. На телефоне в портрете это нормально:
 * сверху журнал, снизу клавиши. Но:
 *
 * • В ЛАНДШАФТЕ на телефоне высота 360 dp. Клавиатура съедает почти всё,
 *   от журнала остаётся полторы строки. Нужно разложить в два столбца.
 *
 * • НА ПЛАНШЕТЕ клавиатура во всю ширину даёт клавиши по 200 dp —
 *   попасть в них с краю экрана невозможно, до дальней руке не дотянуться.
 *   Клавиатуру нужно ограничить по ширине и прижать к краю, за который
 *   держат устройство.
 *
 * • НА РАСКЛАДУШКЕ в раскрытом виде ширина как у планшета, но пропорции
 *   почти квадратные. Здесь уместны две панели: журнал и карточка абонента.
 *
 * ── Пороги ─────────────────────────────────────────────────────────────────
 * Взяты из рекомендаций Material 3 по размерам окна, но с поправкой:
 * для нас важна не только ширина, но и ВЫСОТА — из-за клавиатуры.
 */
object AdaptiveLayout {

    /** Границы Material 3 по ширине окна, в dp. */
    private const val WIDTH_MEDIUM = 600
    private const val WIDTH_EXPANDED = 840

    /** Ниже этой высоты клавиатура не помещается вместе со списком. */
    private const val HEIGHT_COMPACT = 480

    enum class Mode {
        /** Телефон в портрете: журнал сверху, клавиатура снизу. */
        STACKED,

        /** Телефон в ландшафте: журнал слева, клавиатура справа. */
        SIDE_BY_SIDE,

        /** Планшет: журнал слева, справа клавиатура ограниченной ширины. */
        TABLET_DIALPAD,

        /**
         * Большой экран: журнал слева, справа карточка выбранного абонента.
         * Клавиатура вызывается кнопкой поверх.
         */
        TWO_PANE
    }

    /**
     * @param widthDp ширина окна в dp
     * @param heightDp высота окна в dp
     * @param hasSelection выбран ли абонент — влияет на выбор второй панели
     */
    fun modeFor(widthDp: Int, heightDp: Int, hasSelection: Boolean = false): Mode = when {
        /*
         * ВЫСОТА ПРОВЕРЯЕТСЯ ПЕРВОЙ.
         *
         * Раньше первыми шли пороги по ширине, и телефон в ландшафте
         * попадал в планшетную ветку: у современных аппаратов ширина
         * в ландшафте 900 dp и больше, то есть выше порога WIDTH_EXPANDED.
         * Раскладка получалась планшетная — клавиатура ограниченной
         * ширины у края, — на окне высотой 412 dp это не работает.
         *
         * Порядок проверок и есть суть этой функции: низкое окно —
         * всегда телефон в ландшафте, какой бы широкий он ни был.
         * Планшеты и раскладушки в любой ориентации выше 480 dp
         * и в эту ветку не попадают.
         *
         * Ошибку нашёл тест «телефон в ландшафте раскладывает панели
         * в два столбца»: он падал с TABLET_DIALPAD вместо SIDE_BY_SIDE
         * ровно на размерах повёрнутого Pixel 7.
         */
        heightDp < HEIGHT_COMPACT -> Mode.SIDE_BY_SIDE

        // Очень широкий экран: есть место под две содержательные панели.
        // Клавиатура здесь вторична — на планшете чаще ищут в журнале,
        // чем набирают номер вручную
        widthDp >= WIDTH_EXPANDED -> if (hasSelection) Mode.TWO_PANE else Mode.TABLET_DIALPAD

        // Средняя ширина: планшет в портрете или раскладушка
        widthDp >= WIDTH_MEDIUM -> Mode.TABLET_DIALPAD

        else -> Mode.STACKED
    }

    /**
     * Максимальная ширина клавиатуры.
     *
     * Клавиша шире 110 dp выглядит нелепо и требует переставлять палец:
     * рука охватывает примерно 90 мм, а 110 dp × 3 столбца — это уже
     * почти 90 мм на среднем планшете.
     */
    fun dialpadMaxWidthDp(widthDp: Int): Int = when {
        widthDp >= WIDTH_EXPANDED -> 400
        widthDp >= WIDTH_MEDIUM -> 360
        else -> widthDp
    }

    /**
     * Прижимать ли клавиатуру к краю экрана.
     *
     * На широком экране клавиатура по центру недосягаема одной рукой:
     * планшет держат за край. Прижимаем к той стороне, где обычно
     * находится большой палец.
     */
    fun shouldAlignDialpadToEdge(widthDp: Int): Boolean = widthDp >= WIDTH_MEDIUM

    /** Показывать ли журнал и клавиатуру одновременно. */
    fun showsBothPanes(mode: Mode): Boolean = mode != Mode.STACKED

    /**
     * Сколько строк журнала помещается при данной раскладке.
     * Используется для решения, показывать ли пустое состояние
     * крупной иллюстрацией или одной строкой текста.
     */
    fun estimatedVisibleRows(mode: Mode, heightDp: Int): Int {
        val rowHeightDp = 76
        val availableHeight = when (mode) {
            Mode.STACKED -> heightDp / 2       // половину занимает клавиатура
            else -> heightDp - 56              // только панель сверху
        }
        return (availableHeight / rowHeightDp).coerceAtLeast(0)
    }
}
