package com.ogneliss.dialer.ui.components

import androidx.compose.runtime.Immutable
import com.ogneliss.dialer.data.CallLogGroup
import com.ogneliss.dialer.data.CallType

/**
 * ГОТОВОЕ СОСТОЯНИЕ СТРОКИ ЖУРНАЛА.
 *
 * ══════════════════════════════════════════════════════════════════════════
 * ЗАЧЕМ ЭТО НУЖНО: ТОРМОЗА ПРИ ПРОКРУТКЕ
 * ══════════════════════════════════════════════════════════════════════════
 * Причина рывков была не в нехватке кэша данных — журнал уже в памяти.
 * Причина в том, что каждая карточка пересчитывала себя заново
 * на каждом кадре прокрутки:
 *
 *   • форматировался номер через libphonenumber — разбор строки
 *   • собиралась подпись определителя с обращением к ресурсам
 *   • форматировалась дата
 *   • строилось описание для TalkBack конкатенацией строк
 *
 * На экране помещается 8–10 карточек. При прокрутке 60 кадров в секунду
 * это до 600 разборов номера в секунду — при бюджете 16 мс на кадр.
 * Отсюда и рывки.
 *
 * Теперь всё считается ОДИН РАЗ при подготовке списка, а карточка только
 * отрисовывает готовые строки.
 *
 * ── Почему @Immutable ──────────────────────────────────────────────────────
 * Аннотация говорит Compose, что объект не меняется после создания.
 * Тогда при рекомпозиции список сравнивается по ссылке, а не по полям,
 * и карточки, чьи данные не изменились, не перерисовываются вовсе.
 *
 * Без неё Compose вынужден считать содержимое изменившимся при каждом
 * обновлении списка и перерисовывать всё.
 * ══════════════════════════════════════════════════════════════════════════
 */
@Immutable
data class CallLogRowState(
    val key: String,
    val number: String,
    val e164: String,
    val contactId: Long?,

    /** Что показать крупно: имя, заметка или отформатированный номер. */
    val title: String,

    /**
     * Заметка второй строкой — когда есть и имя, и заметка.
     * Если заметка стала заголовком, здесь null: дублировать незачем.
     */
    val noteLine: String?,
    /**
     * Назначено ли напоминание перезвонить.
     *
     * Не часть отпечатка строки: напоминания приходят отдельным потоком
     * и меняются чаще, чем сама запись журнала.
     */
    val hasReminder: Boolean = false,

    /**
     * Метка «спам» или «мошенники» из заметки — подписью, иначе null.
     *
     * Считается при отрисовке, как и пометка блокировки: разбор —
     * в MainDialerScreen рядом с liveRow.
     */
    val warningTag: String? = null,

    /**
     * Заголовок взят из заметки.
     * Интерфейс помечает такие строки иначе: это не имя контакта,
     * и путать их не следует.
     */
    val titleFromNote: Boolean,

    /** Отформатированный номер — всегда, даже когда есть имя. */
    val formattedNumber: String,

    /** Готовая строка даты. */
    val dateLabel: String,

    /** Подпись определителя или null. */
    val infoLabel: String?,
    /**
     * Пометка о блокировке: «Заблокирован — чёрный список».
     *
     * null у обычных вызовов. Показывается вместо подписи определителя:
     * причина блокировки важнее сведений о регионе, а две строки подряд
     * перегружали бы карточку.
     */
    val blockedLabel: String? = null,

    /** Подпись — предупреждение, а не справка. */
    val infoIsWarning: Boolean,

    val photoUri: String?,
    val lastType: CallType,
    val count: Int,
    val incomingCount: Int,
    val outgoingCount: Int,
    val missedCount: Int,
    val hasMissed: Boolean,
    val simLabel: String?,
    val simSlotIndex: Int?,
    val numbersCount: Int,

    /** Готовое описание для TalkBack. */
    val accessibilityLabel: String,

    /**
     * Отпечаток исходных данных.
     *
     * ── Зачем ──────────────────────────────────────────────────────────────
     * По нему решается, можно ли переиспользовать готовую строку
     * при пересборке списка. Сравнение целого числа стоит ничего,
     * тогда как повторная проверка «изменилось ли что-нибудь» через
     * те же функции, что готовят строку, обошлась бы дороже самой
     * подготовки — то есть смысл оптимизации терялся бы полностью.
     *
     * Включает всё, что влияет на вид строки: сама группа, заметка,
     * данные определителя, фотография, слот SIM.
     */
    val signature: Int,

    /** Исходная группа — нужна обработчикам действий. */
    val group: CallLogGroup
)
