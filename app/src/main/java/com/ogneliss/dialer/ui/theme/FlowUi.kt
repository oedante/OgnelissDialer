package com.ogneliss.dialer.ui.theme

import androidx.compose.foundation.layout.PaddingValues
import androidx.compose.ui.unit.dp
import androidx.compose.ui.unit.sp

/**
 * FLOWUI — ОБЩИЕ ПРАВИЛА ОФОРМЛЕНИЯ.
 *
 * ══════════════════════════════════════════════════════════════════════════
 * ЧТО ЭТО
 * ══════════════════════════════════════════════════════════════════════════
 * Набор решений, общих для всех экранов приложения. Не украшение,
 * а способ не принимать одни и те же решения заново на каждом экране —
 * и не получать в итоге три разных отступа для одного и того же.
 *
 * ── Три правила, из которых всё следует ────────────────────────────────────
 *
 * 1. СОДЕРЖИМОЕ В КАРТОЧКАХ. Каждый смысловой блок — своя карточка
 *    на подложке. Границу видно без разделителей и заголовков,
 *    а глаз находит нужное, не читая.
 *
 * 2. ГЛАВНОЕ КРУПНО И СВЕРХУ. На карточке абонента это «Позвонить»,
 *    в журнале — сама запись. Остальное мельче, а редкое — свёрнуто
 *    или в меню.
 *
 * 3. ДОСЯГАЕМОСТЬ ОДНОЙ РУКОЙ. Частые действия внизу экрана,
 *    в пределах большого пальца. Наверху — то, к чему тянутся
 *    осознанно: назад, меню.
 *
 * ── Чего здесь намеренно нет ───────────────────────────────────────────────
 * Цветов. Их задаёт цветовая схема Material, и дублировать её здесь
 * значило бы получить два источника правды: при смене темы один
 * поменяется, другой нет.
 */
object FlowUi {

    /**
     * Отступ между карточками.
     *
     * 4 dp. Было 8 — и на живом экране список выглядел разреженным:
     * между карточками зияли полосы, а на экран помещалось на две
     * записи меньше.
     *
     * Сливаться в полотно они не начинают: у карточки есть подложка
     * и скругление, граница видна и при малом промежутке.
     */
    val cardSpacing = 4.dp

    /**
     * Отступ от края экрана.
     *
     * 12 dp, а не 16: карточка сама добавляет внутренний отступ,
     * и вместе они дают привычные 16 от края до текста — но при этом
     * карточка шире и вмещает больше.
     */
    val screenPadding = 12.dp

    /** Внутренний отступ карточки. */
    val cardPadding = PaddingValues(horizontal = 16.dp, vertical = 8.dp)

    /**
     * ЕДИНЫЕ РАЗМЕРЫ СТРОК И ПУНКТОВ МЕНЮ.
     *
     * ══════════════════════════════════════════════════════════════════════
     * ЗАЧЕМ ВЫНЕСЕНО СЮДА
     * ══════════════════════════════════════════════════════════════════════
     * Высота пункта меню задавалась в MainDialerScreen приватной
     * константой, и другие меню — фильтры в заметках, выбор номера,
     * шторка действий — брали свои значения. Пункты одного вида
     * получались разной высоты, и это видно, когда два меню открывают
     * подряд.
     *
     * Здесь же — минимальная высота строки списка. Строки короче
     * пятидесяти шести точек читаются как сплошной текст, а не как
     * список, и промахнуться по ним легче.
     */
    /*
     * 56 dp числом, а не ссылкой на primaryActionHeight: тот объявлен
     * ниже в этом же объекте, и обращение к нему отсюда вернуло бы
     * ноль — свойства объекта считаются сверху вниз при первом
     * обращении к нему.
     */
    val menuItemHeight = 56.dp

    val menuItemPadding = PaddingValues(horizontal = 16.dp, vertical = 8.dp)

    val rowHeight = 56.dp

    /**
     * Диаметр круга у действия в карточке.
     *
     * 48 dp — обязательный размер нажатия. Нажимается при этом вся
     * колонка вместе с подписью, но сам круг меньше делать нельзя:
     * если человек целится в значок, он должен попасть.
     */
    val actionCircleSize = 48.dp

    /**
     * ВНУТРЕННИЙ ОТСТУП СОДЕРЖИМОГО.
     *
     * ══════════════════════════════════════════════════════════════════════
     * ЗАЧЕМ ОТДЕЛЬНО ОТ screenPadding
     * ══════════════════════════════════════════════════════════════════════
     * screenPadding (12 dp) — расстояние от края экрана до панели.
     * contentPadding (16 dp) — от края панели до её содержимого.
     * Это разные величины, и совпасть они не должны: если сделать их
     * равными, текст окажется ровно под краем соседней панели,
     * и разделение блоков перестанет читаться.
     *
     * Шестнадцать точек стояли числом в тринадцати файлах. Значение
     * верное, но пока оно не названо, следующий экран напишет
     * четырнадцать или восемнадцать — и никто не заметит.
     */
    val contentPadding = 16.dp

    /**
     * ОТСТУП ВНУТРИ ШТОРКИ.
     *
     * ── Почему больше, чем у списков ───────────────────────────────────────
     * Шторка не занимает весь экран: у неё есть края, и содержимое
     * не должно к ним прижиматься. В списке край экрана служит
     * границей сам по себе, здесь — нет.
     *
     * 20 dp: меньше прежних 24, потому что при них шторка фильтров
     * не вмещала все разделы без прокрутки, и больше 12 из списков,
     * потому что прижатое к краю содержимое выглядит теснее.
     */
    val sheetPadding = 20.dp

    /**
     * ОТСТУП СНИЗУ У ШТОРКИ.
     *
     * Шторка упирается в нижний край экрана, где на большинстве
     * телефонов проходит полоса жеста навигации. Без запаса последний
     * пункт оказывается под ней, и нажать по нему трудно.
     *
     * 24 dp — высота полосы плюс немного.
     */
    val sheetBottomPadding = 24.dp

    /**
     * Высота главной кнопки действия.
     *
     * 56 dp — заметно больше рядовых 48. По ней попадают не глядя:
     * «Позвонить» на карточке, «Ответить» на входящем.
     */
    val primaryActionHeight = 56.dp

    /**
     * Наименьшая ширина кнопок «Ответить», «Отклонить», «Завершить».
     *
     * Было число 150 прямо в разметке — единственное трёхзначное
     * в файле и единственное не по сетке. Значение оставлено прежним:
     * оно подобрано так, чтобы «Отклонить» и «Ответить» помещались
     * рядом на экране 360 dp и при этом были шире, чем расстояние
     * между ними.
     */
    val callActionMinWidth = 152.dp

    /**
     * ДВЕ РАЗНЫЕ ШКАЛЫ: ОТСТУПЫ И ЗНАЧКИ.
     *
     * Отступы кратны четырём: 4, 8, 12, 16, 24, 32. Это сетка,
     * и отклонение от неё видно как неровность.
     *
     * Размеры значков — своя шкала: 14, 16, 18, 20, 24. Она не обязана
     * совпадать с сеткой отступов: значок 18 dp рядом с текстом
     * bodySmall смотрится ровно, а 16 или 20 — уже мелко или крупно.
     * Материал использует ту же логику: 18 dp — стандартный значок
     * внутри кнопки, 24 dp — отдельно стоящий.
     *
     * Проверка «всё кратно четырём» поэтому применяется только
     * к отступам. Значки проверяются глазом и этим списком.
     */
    val iconSizeSmall = 14.dp
    val iconSizeInline = 18.dp
    val iconSizeDefault = 24.dp

    /**
     * Размер кнопки быстрого действия.
     *
     * Это ряд под главной кнопкой: SMS, напоминание, блокировка.
     * 48 dp — рекомендованный минимум, и увеличивать его незачем:
     * в ряд их помещается четыре, а не три.
     */
    val quickActionSize = 44.dp

    /**
     * ВЫСОТА РЯДА В НИЖНЕЙ ПАНЕЛИ.
     *
     * Общая для журнала и контактов. До этого каждая панель набирала
     * высоту из своего содержимого: в журнале это кнопка клавиатуры
     * 52 dp плюс отступы, в контактах — поле поиска 56 dp плюс свои.
     * Панели различались на десяток точек, и при переходе между
     * экранами нижний край заметно дёргался.
     *
     * 68 dp = 52 + 8 + 8, то есть прежняя высота журнала: он —
     * основной экран, и подстраивать надо под него, а не наоборот.
     * Поле поиска (56 dp) внутрь помещается.
     */
    /*
     * 72 dp, а не 68: под кнопками панели появились подписи.
     *
     * Самая высокая кнопка — клавиатура в журнале: 52 dp кнопки,
     * 2 dp зазора и строка подписи (16 dp высоты строки у labelSmall) —
     * всего 70. Поле поиска на остальных панелях — 56 dp, кнопка фильтра
     * с подписью — 46. Одно значение на все четыре панели держит их
     * одинаковыми: при переходе между экранами край панели не прыгает.
     */
    // Кнопка с подписью: таблетка 40 + зазор 4 + подпись 16 = 60.
    // С 1.2.0 все кнопки ряда одной высоты, и 72 хватает с запасом
    val bottomPanelRowHeight = 72.dp

    /**
     * Высота строки нижней панели для текущего окна.
     *
     * На телефоне лёжа высоты ~360 dp на всё, и панель в 72 dp с полоской
     * и отступами съедала четверть экрана. Там подписи под кнопками
     * прячутся (LabeledIconButton), и строке хватает 60 dp: поле поиска —
     * 56, круглая кнопка клавиатуры — 52.
     *
     * Функция, а не число: значение зависит от окна, а окно известно
     * только внутри Compose.
     */
    @androidx.compose.runtime.Composable
    fun panelRowHeight(): androidx.compose.ui.unit.Dp =
        // Без подписей строке хватает высоты самой кнопки — как лёжа
        if (com.ogneliss.dialer.ui.adaptive.LocalWindowLayout.current.isShort ||
            !LocalAppearance.current.buttonLabels
        ) 60.dp
        else bottomPanelRowHeight

    /**
     * ВЫСОТА ПОЛОСКИ-НАМЁКА НАД РЯДОМ КНОПОК.
     *
     * В журнале над кнопками есть полоска, за которую вытягивается
     * клавиатура: сама она 4 dp, плюс по 8 dp отступов, чтобы в неё
     * можно было попасть пальцем.
     *
     * В контактах вытягивать нечего, и полоски там нет — но высоту
     * она занимает, и без неё панель контактов оказывалась на 20 dp
     * ниже журнальной. При переходе между экранами нижний край
     * подпрыгивал.
     *
     * Поэтому в контактах это место просто пустое: рисовать полоску,
     * которая ничего не тянет, нельзя — она обещает жест, которого нет.
     */
    val bottomPanelHandleHeight = 20.dp

    /**
     * РАЗМЕРЫ ТЕКСТА НА ЭКРАНЕ ВЫЗОВА.
     *
     * ── Почему уменьшены ───────────────────────────────────────────────────
     * Было 36/28/18. Рядом с журналом и контактами экран вызова выглядел
     * из другого приложения: там заголовки 22 sp, здесь имя было почти
     * вдвое крупнее. Крупный шрифт при этом не помогал — он вытеснял
     * с экрана всё остальное, и длинное имя занимало три строки.
     *
     * Теперь 28/22/16 — это headlineMedium, titleLarge и bodyLarge
     * типографической шкалы. Имя по-прежнему крупнейшее на экране,
     * но разница с остальным приложением стала соразмерной.
     *
     * Единственное место в приложении, где шрифт задаётся числом,
     * а не стилем темы: имя звонящего должно быть крупнее всего,
     * что есть в типографической шкале, — его читают в спешке,
     * искоса, доставая телефон из кармана.
     *
     * Числа вынесены сюда, чтобы их было видно рядом с остальными
     * размерами. Раньше они стояли прямо в разметке экрана, и любая
     * правка требовала помнить, что таких мест несколько:
     * портретная раскладка, альбомная и номер под именем.
     *
     * ⚠️ Это исключение, а не пример. Везде остальное — стили темы.
     */
    val callNameSize = 28.sp
    val callNameSizeLandscape = 22.sp
    val callNumberSize = 16.sp

    /**
     * Портрет в шапке карточки.
     *
     * 88 dp: заметно меньше прежних 112, потому что рядом теперь
     * стоит кнопка «Позвонить», и вместе они не должны занимать
     * половину экрана.
     */
    val headerAvatarSize = 72.dp

    /**
     * ПОРТРЕТ В СВОРАЧИВАЮЩЕЙСЯ ШАПКЕ.
     *
     * 160 dp — крупно, но не 200 из макета: там портрет во всю ширину
     * экрана, а у нас он живёт в шапке рядом с кнопками «назад»
     * и «избранное». Во всю ширину он бы их подпирал.
     *
     * Смысл при этом сохраняется: лицо узнаётся мгновенно, и вопрос
     * «с кем я говорю» отпадает до чтения имени.
     */
    val headerPortraitSize = 160.dp

    /**
     * ПОРТРЕТ НА ЭКРАНЕ ВЫЗОВА.
     *
     * ── Почему уменьшен со 180 до 132 ──────────────────────────────────────
     * 180 dp занимали верхнюю треть экрана, и вместе с крупным именем
     * это выглядело как отдельное приложение рядом с журналом,
     * где строка контакта — 48 dp. Пустоты стало не меньше: она просто
     * переехала вниз, между именем и кнопками.
     *
     * 132 dp — портрет по-прежнему крупнейший элемент экрана и узнаётся
     * с вытянутой руки, но верх больше не съеден. При длинном имени
     * в три строки это разница между «влезло» и «не влезло».
     *
     * ── Почему не во всю ширину ────────────────────────────────────────────
     * Тогда имя ушло бы под кнопки, а при входящем звонке оно важнее
     * фотографии: по нему решают, брать ли трубку.
     */
    val callPortraitSize = 132.dp

    /**
     * Портрет в альбомной ориентации.
     *
     * По высоте места вдвое меньше, и крупный портрет вытеснил бы
     * имя за край.
     */
    val callPortraitSizeLandscape = 88.dp

    /**
     * Сколько записей истории показывать свёрнутой.
     *
     * Четыре: хватает понять, когда общались в последний раз,
     * и остаётся место под то, что ниже.
     */
    const val COLLAPSED_HISTORY = 4
}
