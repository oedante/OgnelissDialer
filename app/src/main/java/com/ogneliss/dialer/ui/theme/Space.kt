package com.ogneliss.dialer.ui.theme

import androidx.compose.ui.unit.dp

/**
 * Шкала отступов (1.3.4, 04.10.2026, фаза 4 — дизайн-система).
 *
 * Было: около 340 отступов числами прямо в экранах (padding, Spacer,
 * spacedBy, PaddingValues). 301 из них уже стояли на шкале 4 · 8 · 12 ·
 * 16 · 24 · 32 dp — шкала взята из фактического использования (аудит,
 * «Дизайн-система»), а не придумана. Теперь это имена: решение «какой
 * отступ» принимается выбором ступени, а не подбором числа.
 *
 * Значения вне шкалы (2, 6, 20 dp…) намеренно не тронуты: свести их
 * к шкале — значит изменить вид, это решение «под глаз» для каждого места.
 * Новые отступы — только отсюда; prebuild_check предупреждает о числе
 * со шкалы в отступе.
 *
 * Компонентные размеры (поля экрана, карточки, шторки, высота строки)
 * — в FlowUi и Dimens: они собраны из этих же ступеней.
 */
object Space {
    /** 4 dp — между карточками, между значком и подписью. */
    val xs = 4.dp
    /** 8 dp — внутри плотных групп, вертикальное поле карточки. */
    val s = 8.dp
    /** 12 dp — поля экрана, между блоками внутри панели. */
    val m = 12.dp
    /** 16 dp — горизонтальное поле карточки и панели. */
    val l = 16.dp
    /** 24 dp — между разделами, нижнее поле шторки. */
    val xl = 24.dp
    /** 32 dp — крупные разрывы: пустые состояния, конец списка. */
    val xxl = 32.dp
}
