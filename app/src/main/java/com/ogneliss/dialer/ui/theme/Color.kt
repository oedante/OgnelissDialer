/**
 * ЦВЕТ ВЫЗОВА.
 *
 * ── Почему вынесен сюда ────────────────────────────────────────────────────
 * Он был приватным внутри фабрики свайпов, и кнопке «Позвонить»
 * в карточке пришлось бы задать свой зелёный. Два оттенка для одного
 * действия — верный способ получить расхождение при следующей правке:
 * поправят один, забудут другой.
 *
 * Затемнён относительно обычного зелёного: на нём лежит белый текст,
 * и светлый давал бы контраст ниже 4.5:1.
 */
