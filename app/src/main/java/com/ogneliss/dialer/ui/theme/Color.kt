 * СВОЯ ПАЛИТРА от оранжевого логотипа делала приложение узнаваемым,
 * но чужеродным: рядом с системными приложениями оно выглядело гостем,
 * а тёплые серые фоны читались как выцветшие.
 *
 * ЦВЕТА ИЗ ОБОЕВ (Material You) дают непредсказуемый результат: при одних
 * обоях интерфейс получается контрастным, при других — блёклым, и никакой
 * возможности это проверить у нас нет. Диалером пользуются в спешке,
 * и читаемость здесь важнее индивидуальности.
