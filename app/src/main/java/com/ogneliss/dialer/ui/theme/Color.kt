/**
 * ЦВЕТ ОТКЛОНЕНИЯ И ЗАВЕРШЕНИЯ.
 *
 * ── Почему рядом с CallGreen ───────────────────────────────────────────────
 * Красный «отклонить» и зелёный «ответить» — пара: их видят вместе
 * и различают по цвету за доли секунды. Держать их в разных файлах
 * значит однажды поправить один и оставить другой.
 *
 * ── Про оттенок ────────────────────────────────────────────────────────────
 * На экране вызова стоял 0xFFE53935, а в фабрике свайпов —
 * 0xFFC62828. Разница видна, если положить рядом: одно действие
 * выглядело по-разному в зависимости от того, откуда его вызвали.
 *
 * Взят более тёмный: на нём лежит белый текст, и светлый давал
 * контраст ниже 4.5:1.
 */
internal val DeclineRed = androidx.compose.ui.graphics.Color(0xFFC62828)

/**
 * ЦВЕТ ЗНАЧКА ЗАМЕТКИ.
 *
 * ══════════════════════════════════════════════════════════════════════════
 * ПОЧЕМУ ПРИГЛУШЁННЫЙ БИРЮЗОВЫЙ
 * ══════════════════════════════════════════════════════════════════════════
 * Значок «i» стоит вместо силуэта у номеров, которых нет в книге,
 * но для которых есть заметка. Среди серых значков он терялся:
 * человек не замечал, что подпись — его собственная пометка,
 * а не имя из книги.
 *
 * ── Почему не зелёный, как вызов ───────────────────────────────────────────
 * Зелёный в приложении означает одно: «позвонить». Он на кнопке
 * вызова, на свайпе, на трубке в строке. Использовать его для метки
 * значило бы намекнуть на действие, которого нет.
 *
 * Бирюзовый рядом с зелёным по тону — заметен так же, но не путается
 * с ним. И он не занят ничем другим: красный у блокировки, синий
 * у счётчиков, серый у обычного.
 *
 * ── Почему приглушённый ────────────────────────────────────────────────────
 * Значок поясняет, а не требует внимания. Яркий притягивал бы взгляд
 * сильнее имени, ради которого строку и читают.
 */
