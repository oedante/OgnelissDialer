/**
 * БЛОКИРОВКА — КРАСНЫЙ, СНЯТИЕ — ЗЕЛЁНЫЙ.
 *
 * ══════════════════════════════════════════════════════════════════════════
 * ЗАЧЕМ ОТДЕЛЬНЫЕ ИМЕНА, А НЕ error И CallGreen НАПРЯМУЮ
 * ══════════════════════════════════════════════════════════════════════════
 * Блокировка — единственное необратимое на вид действие в приложении:
 * человек не узнает о звонках, которые оно отрежет. Цвет здесь несёт
 * смысл «осторожно», и он должен быть одинаковым везде: в карточке,
 * в меню длинного нажатия, в списках правил, на экране после звонка.
 *
 * Пока цвет брали кто откуда — один экран из colorScheme.error, другой
 * из DeclineRed, — расхождение было неизбежным. Теперь у обоих действий
 * своё имя, и смена оттенка меняет его во всех местах сразу.
 *
 * ── Почему это те же цвета, что у телефонии ────────────────────────────────
 * DeclineRed — цвет кнопки «Отклонить», CallGreen — «Ответить». Человек
 * уже связал их со смыслом «отрезать звонок» и «принять звонок»;
 * блокировка и разблокировка — то же самое, только надолго.
 *
 * ⚠️ Оба проверены на контраст с тёмной и светлой подложкой панели
 * действий. Менять оттенок — проверять заново: на светло-серой плитке
 * яркий красный выглядит тревожнее, чем нужно, а бледный теряется.
 */
