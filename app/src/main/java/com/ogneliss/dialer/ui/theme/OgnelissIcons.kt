/** Material Symbols: viewBox "0 -960 960 960" — сдвиг на 960 по вертикали. */
private fun rounded(name: String, autoMirror: Boolean = false, block: PathBuilder.() -> Unit): ImageVector =
    ImageVector.Builder(
        name = name,
        defaultWidth = 24.dp,
        defaultHeight = 24.dp,
        viewportWidth = 960f,
        viewportHeight = 960f,
        autoMirror = autoMirror
    ).group(translationY = 960f) {
        path(fill = SolidColor(Color.Black), pathBuilder = block)
    }.build()

/** Залитые иконки старого формата Symbols: координаты 24 × 24 без viewBox. */
