 * (холодный запуск, замер startupNoCompilation) разбор чисел из строк
 * заметно медленный: холодный запуск +15% (276 против 239 мс). Стало —
 * как в библиотеке Google material-icons: moveTo/lineTo/curveTo в коде,
 * числа — константы. Пути переведены svgpathtools в абсолютные координаты
 * (scripts/build_icons.py).
