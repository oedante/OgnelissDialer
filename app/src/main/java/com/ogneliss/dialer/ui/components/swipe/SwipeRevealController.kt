package com.ogneliss.dialer.ui.components.swipe

import androidx.compose.runtime.Composable
import androidx.compose.runtime.getValue
import androidx.compose.runtime.mutableStateOf
import androidx.compose.runtime.setValue
import androidx.compose.runtime.remember

/**
 * КООРДИНАТОР РАСКРЫТЫХ ПАНЕЛЕЙ.
 *
 * Назначение: следит, чтобы в списке была раскрыта максимум одна панель.
 *
 * ── Зачем это нужно ────────────────────────────────────────────────────────
 * Без координатора пользователь свайпает по трём строкам подряд и получает
 * три открытые панели. Экран превращается в кашу, а следующий свайп
 * непонятно к чему относится. Все известные списки с раскрывающимися
 * действиями (почтовые клиенты, мессенджеры) держат открытой одну строку.
 *
 * Дополнительно панель закрывается:
 *  • при прокрутке списка — палец ушёл, намерение изменилось;
 *  • после выполнения действия;
 *  • при нажатии на саму строку.
 */
class SwipeRevealController {

    /** Ключ строки с раскрытой панелью. null — все закрыты. */
    var openKey by mutableStateOf<String?>(null)
        private set

    fun open(key: String) {
        openKey = key
    }

    fun close() {
        openKey = null
    }

    fun closeIfOpen(key: String) {
        if (openKey == key) openKey = null
    }

    fun isOpen(key: String): Boolean = openKey == key

    /**
     * СЧЁТЧИК КОМАНД «ЗАКРЫТЬ ВСЁ».
     *
     * ── Зачем счётчик, а не флаг ───────────────────────────────────────────
     * Строке нужно узнать не «закрыто ли сейчас», а «поступила ли новая
     * команда». Флаг для этого не годится: он может быть уже сброшен
     * к моменту, когда строка его прочитает, — и команда потеряется.
     *
     * Счётчик растёт, и любое его изменение строка замечает независимо
     * от того, в каком она была состоянии.
     *
     * ── Зачем это понадобилось ─────────────────────────────────────────────
     * Строка возвращается на место анимацией, а анимацию может прервать
     * что угодно: появился диалог, приложение ушло в фон, пришёл входящий.
     * Тогда карточка застывает сдвинутой — именно это и происходило
     * при отмене выбора SIM.
     *
     * Команда «закрыть всё» действует детерминированно: неважно, что
     * случилось с анимацией, строка встанет на место.
     */
    var closeAllToken by mutableStateOf(0)
        private set

    /**
     * Закрыть все строки.
     *
     * Вызывается там, где сдвинутая строка точно не нужна: при закрытии
     * диалога, при возвращении в приложение, при уходе с экрана.
     */
    fun closeAll() {
        openKey = null
        closeAllToken++
    }
}

@Composable
fun rememberSwipeRevealController(): SwipeRevealController =
    remember { SwipeRevealController() }
