package com.ogneliss.dialer.util

import com.google.i18n.phonenumbers.PhoneNumberUtil

object PhoneFormatter {

    /**
     * КЭШ ОТФОРМАТИРОВАННЫХ НОМЕРОВ.
     *
     * ── Почему он нужен ────────────────────────────────────────────────────
     * libphonenumber при форматировании разбирает строку, определяет
     * регион по офлайн-справочнику и подбирает шаблон. Операция недорогая
     * по отдельности, но одни и те же номера форматируются снова и снова:
     * при подгрузке страницы журнала пересобирается весь список, и номера
     * с первой страницы разбираются заново.
     *
     * У активного пользователя в журнале десятки уникальных номеров
     * и сотни записей — то есть каждый номер разбирается по многу раз.
     *
     * ── Почему кэш ОГРАНИЧЕН ───────────────────────────────────────────────
     * Безразмерный кэш здесь был бы ошибкой: журнал грузится страницами
     * до трёх тысяч записей, и хранить всё означало бы держать в памяти
     * строки, которые больше не понадобятся.
     *
     * 512 записей покрывают несколько экранов прокрутки в обе стороны
     * с запасом. При переполнении вытесняется самая давняя — она
     * с наибольшей вероятностью уже уехала за пределы экрана.
     *
     * ── Про потокобезопасность ─────────────────────────────────────────────
     * Форматирование вызывается из фонового потока при подготовке строк
     * и изредка из композиции. LinkedHashMap не потокобезопасен, поэтому
     * доступ синхронизирован. Блокировка короткая: чтение из map
     * несопоставимо дешевле разбора номера, ради которого всё и делается.
     */
    private const val CACHE_SIZE = 512

    private val formatCache = object : LinkedHashMap<String, String>(
        CACHE_SIZE, 0.75f, /* accessOrder = */ true
    ) {
        override fun removeEldestEntry(eldest: MutableMap.MutableEntry<String, String>) =
            size > CACHE_SIZE
    }

    private val cacheLock = Any()

    /**
     * СТРАНА, ПО ПРАВИЛАМ КОТОРОЙ РАЗБИРАЮТСЯ МЕСТНЫЕ НОМЕРА.
     *
     * ══════════════════════════════════════════════════════════════════════
     * ЗАЧЕМ ЭТО ПОЛЕ
     * ══════════════════════════════════════════════════════════════════════
     * Во всех функциях здесь страна была вписана строкой «RU». Пока
     * приложение было русским, это не мешало. С четырьмя языками мешает:
     * номер «030 12345678», набранный в Берлине, по российским правилам
     * не разбирается, а значит не приводится к E.164.
     *
     * А E.164 — ключ, по которому живёт половина приложения: заметки,
     * правила блокировки, напоминания, сведение дублей. Номер, который
     * не привёлся, не совпадёт сам с собой, записанным иначе.
     *
     * Значение ставится один раз при запуске (OgnelissApp) по SIM-карте.
     * @Volatile — его читают из потоков разбора журнала, а пишут
     * из главного.
     *
     * ⚠️ Менять в работающем приложении нельзя без clearCache():
     * в ключах кэша страна есть, но форматирование уже отданных строк
     * не переделается.
     */
    @Volatile
    var defaultRegion: String = "RU"
        private set

    /** Вызывается один раз при запуске. */
    fun setDefaultRegion(region: String) {
        val normalized = region.uppercase(java.util.Locale.ROOT)
        if (normalized.isBlank() || normalized == defaultRegion) return
        defaultRegion = normalized
        clearCache()
    }

    /** Сброс кэша. Нужен при смене региона: шаблоны форматирования другие. */
    fun clearCache() {
        synchronized(cacheLock) { formatCache.clear() }
    }
    private val util: PhoneNumberUtil by lazy { PhoneNumberUtil.getInstance() }

    /**
     * Национальный вид: 8 (967) 111-22-33
     *
     * Результат кэшируется: разбор через libphonenumber — самая дорогая
     * операция при подготовке списка, и одни и те же номера
     * форматируются многократно.
     */
    fun format(raw: String, region: String = defaultRegion): String {
        if (raw.isBlank()) return raw

        // Ключ включает регион: один номер в разных регионах форматируется
        // по-разному, и общий ключ давал бы неверный результат
        val key = "N|$region|$raw"
        synchronized(cacheLock) { formatCache[key] }?.let { return it }

        val result = try {
            val parsed = util.parse(raw, region)

            /*
             * ══════════════════════════════════════════════════════════════
             * ЧТО ПРИШЛО С КОДОМ СТРАНЫ — С НИМ И ОСТАЁТСЯ
             * ══════════════════════════════════════════════════════════════
             * Раньше здесь всегда стоял NATIONAL, и «+7 967 111-22-33»
             * превращалось в «8 (967) 111-22-33». Для России это привычная
             * запись, но она подменяет то, что человек видел: восьмёрка —
             * российский префикс выхода на межгород, и к номеру он
             * отношения не имеет.
             *
             * За пределами России такая подмена уже вредна. NATIONAL
             * у немецкого номера даёт «030 12345678» — без кода страны
             * и без понимания, откуда звонок; у американского «(415)
             * 555-1212». Если номер пришёл международным, человек
             * потерял бы главное: из какой он страны.
             *
             * Правило простое и работает везде: номер, записанный
             * с кодом страны, показывается с кодом страны. Номер,
             * набранный локально, — в местной записи.
             *
             * Отдельно: INTERNATIONAL для своей же страны читается
             * не хуже национальной записи, а для чужой — единственно
             * верно. Поэтому «+7 967 111-22-33» и остаётся собой.
             */
            val format = if (raw.trimStart().startsWith("+")) {
                PhoneNumberUtil.PhoneNumberFormat.INTERNATIONAL
            } else {
                PhoneNumberUtil.PhoneNumberFormat.NATIONAL
            }

            util.format(parsed, format)
        } catch (_: Exception) {
            raw
        }

        synchronized(cacheLock) { formatCache[key] = result }
        return result
    }

    /**
     * E.164 — единый ключ сравнения номеров между журналом и контактами.
     *
     * Кэшируется по той же причине: этот вызов идёт на каждое сравнение
     * номера с контактами, то есть чаще форматирования.
     */
    fun toE164(raw: String, region: String = defaultRegion): String {
        if (raw.isBlank()) return raw

        val key = "E|$region|$raw"
        synchronized(cacheLock) { formatCache[key] }?.let { return it }

        val result = try {
            util.format(util.parse(raw, region), PhoneNumberUtil.PhoneNumberFormat.E164)
        } catch (_: Exception) {
            /*
             * БУКВЕННЫЙ ОТПРАВИТЕЛЬ — НЕ ПУСТАЯ СТРОКА (2.1.3).
             *
             * Отзыв с форума: «на все SMS с буквенным коротким именем (МЧС,
             * МегаФон) подставляет контакт оптики». Было: у адреса без цифр
             * («RSCHS», «MegaFon») оставались только цифры и «+» — то есть
             * пустая строка. У контакта в поле номера стояло «BRAVOOPTICA» —
             * тоже пустая строка; все карты «номер → контакт» в приложении
             * (список SMS, журнал, карточка, заметки) считали их одним
             * номером, и любой буквенный отправитель получал имя и фото
             * этого контакта.
             *
             * Стало: адрес с буквами, который не разобрался как номер,
             * остаётся самим собой — «RSCHS» и «BRAVOOPTICA» разные ключи,
             * а SMS от «BRAVOOPTICA» по праву находит свой контакт. Регистр
             * не трогаем: закрепления и архив SMS уже хранят такие адреса
             * как есть.
             */
            if (raw.any { it.isLetter() }) raw.trim()
            else raw.filter { it.isDigit() || it == '+' }
        }

        synchronized(cacheLock) { formatCache[key] = result }
        return result
    }
}
