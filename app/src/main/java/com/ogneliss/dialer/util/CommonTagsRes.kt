package com.ogneliss.dialer.util

import com.ogneliss.dialer.R

/**
 * Метки хранятся в базе стабильными ключами, а показываются локализованно.
 * Так пользовательская метка не «сломается» при смене языка.
 */
object TagCatalog {

    data class Tag(val key: String, val labelRes: Int)

    /**
     * ОСТАЛИСЬ ТОЛЬКО РАБОТАЮЩИЕ МЕТКИ.
     *
     * ══════════════════════════════════════════════════════════════════════
     * ПОЧЕМУ УБРАЛИ ОСТАЛЬНЫЕ ДЕВЯТЬ
     * ══════════════════════════════════════════════════════════════════════
     * Было одиннадцать: опрос, реклама, банк, доставка, работа, врач,
     * такси, ЖКХ. Ни одна из них ни на что не влияла — просто
     * подписывалась к номеру и там оставалась.
     *
     * Человек тратил время на выбор, ожидая, что метка что-то изменит:
     * отфильтрует, подсветит, напомнит. Не менялось ничего, и заметка
     * с меткой «врач» ничем не отличалась от заметки со словом «врач».
     *
     * ── Что делают оставшиеся две ──────────────────────────────────────────
     * • «спам» и «мошенники» включают автоблокировку, если она
     *   разрешена в настройках;
     * • они же защищают заметку от автоочистки: пометку о мошеннике
     *   нельзя терять по сроку давности.
     *
     * ── Если понадобится своя метка ────────────────────────────────────────
     * Для этого есть текст заметки: он ищется наравне с именем
     * и номером, и «врач» находится набором «врач». Метка была бы
     * вторым способом сделать то же самое.
     */
    val suggested = listOf(
        Tag("spam", R.string.tag_spam),
        Tag("fraud", R.string.tag_fraud)
    )

    fun labelResFor(key: String): Int? = suggested.firstOrNull { it.key == key }?.labelRes
}
