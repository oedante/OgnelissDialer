package com.ogneliss.dialer.util

import java.util.Locale

/**
 * ВЫБОР ЯЗЫКА ПРИ ПЕРВОМ ЗАПУСКЕ.
 *
 * Чистая логика без Android — покрыта тестами.
 *
 * ── Зачем это вообще нужно ─────────────────────────────────────────────────
 * Android сам подставляет язык из системы, если для него есть ресурсы.
 * Но выбор пользователя мы храним отдельно, и до первого явного выбора
 * там пусто. В этом состоянии интерфейс следует за системой — что верно,
 * пока язык системы нам знаком.
 *
 * Проблема начинается, когда язык системы нам незнаком: скажем,
 * казахский. Android возьмёт базовую локаль — английскую, — но настройка
 * приложения останется пустой, и человек увидит «Системный» напротив
 * английского интерфейса. Понять из этого, что происходит, невозможно.
 *
 * Поэтому при первом запуске выбор проставляется явно: либо язык системы,
 * если он поддержан, либо английский.
 *
 * ── Почему сравниваем только код языка ─────────────────────────────────────
 * Система может отдать «ru-RU», «ru-KZ» или «ru-BY» — это всё русский,
 * и переводить его отдельно для каждой страны мы не собираемся.
 * Сравнение по полному тегу отсеяло бы русскоязычного пользователя
 * из Казахстана на английский, что абсурдно.
 */
object LocaleMatcher {

    /** Язык по умолчанию, когда система говорит на незнакомом. */
    const val FALLBACK = "en"

    /**
     * Подбор языка приложения.
     *
     * @param systemTags языки системы в порядке предпочтения пользователя
     * @param supported языки, для которых у нас есть переводы
     */
    fun choose(systemTags: List<String>, supported: List<String>): String {
        if (supported.isEmpty()) return FALLBACK

        // Порядок системных языков — это предпочтения пользователя:
        // на Android можно задать список, и первый совпавший должен
        // выиграть. Перебирать наоборот значило бы навязать ему
        // второй язык вместо первого
        systemTags.forEach { systemTag ->
            val systemLanguage = languageOf(systemTag)
            supported.firstOrNull { languageOf(it) == systemLanguage }
                ?.let { return it }
        }

        // Английский, если он есть среди поддержанных; иначе первый
        // из списка — приложение без интерфейса оставить нельзя
        return supported.firstOrNull { languageOf(it) == FALLBACK }
            ?: supported.first()
    }

    /**
     * Код языка из тега.
     *
     * «ru-RU» → «ru», «zh-Hans-CN» → «zh». Регион и письменность
     * отбрасываем: переводы у нас по языкам, а не по странам.
     */
    fun languageOf(tag: String): String =
        tag.substringBefore('-').lowercase(Locale.ROOT)

    /** Поддержан ли язык системы. Для решения, показывать ли пояснение. */
    fun isSupported(systemTags: List<String>, supported: List<String>): Boolean {
        val supportedLanguages = supported.map { languageOf(it) }.toSet()
        return systemTags.any { languageOf(it) in supportedLanguages }
    }
}
