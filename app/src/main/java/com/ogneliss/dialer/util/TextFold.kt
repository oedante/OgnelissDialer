package com.ogneliss.dialer.util

/**
 * СРАВНЕНИЕ ТЕКСТА ДЛЯ ПОИСКА БУКВАМИ (1.6.0).
 *
 * ══════════════════════════════════════════════════════════════════════════
 * ЗАЧЕМ
 * ══════════════════════════════════════════════════════════════════════════
 * До 1.6.0 журнал искал только цифрами — T9 на клавиатуре набора. В 1.6.0
 * у панели появилась кнопка «Поиск» с обычной клавиатурой, и запрос
 * буквами («сантехник», «Ольга») должен находить имена и заметки.
 *
 * Сравнение — без учёта регистра и с «ё» = «е»: «Семён» находится
 * по «семен», как в системной книге контактов. Букву «ё» пишут не все,
 * и запрос без неё не должен проигрывать имени с ней — и наоборот.
 *
 * ── Почему посимвольно, а не lowercase() всей строки ───────────────────────
 * lowercase() строки может изменить её длину (турецкая «İ» становится
 * двумя символами), и позиция совпадения разошлась бы с исходной
 * строкой — а по ней подсвечивается найденное в имени (HighlightedName).
 * Посимвольное сравнение держит позиции один к одному.
 */
object TextFold {

    /** Символ для сравнения: строчный, «ё» — как «е». */
    fun fold(c: Char): Char = when (val lower = c.lowercaseChar()) {
        'ё' -> 'е'
        else -> lower
    }

    /**
     * Позиция первого вхождения [query] в [text] без учёта регистра
     * и с «ё» = «е»; −1 — нет. Пустой запрос не находит ничего:
     * «совпадение с пустотой» подсветило бы пустой кусок.
     */
    fun indexOf(text: String, query: String, from: Int = 0): Int {
        if (query.isEmpty() || query.length > text.length) return -1
        outer@ for (i in from.coerceAtLeast(0)..text.length - query.length) {
            for (j in query.indices) {
                if (fold(text[i + j]) != fold(query[j])) continue@outer
            }
            return i
        }
        return -1
    }

    /** Есть ли [query] в [text] — разбор у [indexOf]. */
    fun contains(text: String?, query: String): Boolean =
        text != null && indexOf(text, query) >= 0

    /**
     * Запрос — текст, а не номер: в нём есть буквы. Цифры и знаки набора
     * («+», «*», «#») ищутся как раньше — по T9 и номеру.
     */
    fun isTextQuery(query: String): Boolean = query.any { it.isLetter() }

    /**
     * Насколько хорошо имя подходит к запросу — для порядка выдачи:
     * 0 — имя начинается с запроса, 1 — с него начинается слово в имени
     * («петр» → «Иван Петров»), 2 — совпадение внутри слова, 3 — нет
     * совпадения. Смотрятся все вхождения: в «Иван Ванин» запрос «ван»
     * сначала встречается внутри «Иван», но «Ванин» с него начинается.
     */
    fun rank(name: String, query: String): Int {
        var best = 3
        var at = indexOf(name, query)
        while (at >= 0 && best > 0) {
            val r = when {
                at == 0 -> 0
                !name[at - 1].isLetterOrDigit() -> 1
                else -> 2
            }
            if (r < best) best = r
            at = indexOf(name, query, at + 1)
        }
        return best
    }
}
