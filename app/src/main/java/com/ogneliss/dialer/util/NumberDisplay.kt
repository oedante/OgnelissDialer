package com.ogneliss.dialer.util

/**
 * ОТОБРАЖЕНИЕ НОМЕРОВ В КОМПАКТНЫХ МЕСТАХ.
 *
 * Когда у абонента несколько номеров, в кнопке или чипе не помещается
 * весь номер. Нужен короткий, но узнаваемый идентификатор.
 *
 * ── Почему последние 4 цифры ───────────────────────────────────────────────
 * Люди запоминают именно окончание номера — «который на 05-12».
 * Код оператора у номеров одного человека часто совпадает и различающей
 * силы не имеет, а последние четыре цифры почти всегда уникальны
 * в пределах одной записной книжки.
 *
 * ── Когда цифр недостаточно ────────────────────────────────────────────────
 * Если у номеров есть осмысленные подписи из телефонной книги
 * («Рабочий», «Домашний»), лучше показывать их: подпись понятнее цифр.
 * Цифры — запасной вариант, когда подписи нет или она неинформативна.
 */
object NumberDisplay {

    /** Последние 4 цифры: "8 (967) 666-05-12" → "0512". */
    fun lastFour(number: String): String =
        number.filter { it.isDigit() }.takeLast(4)

    /** Форматированные последние цифры для чипа: "…05-12". */
    fun shortLabel(number: String): String {
        val digits = lastFour(number)
        if (digits.length < 4) return digits
        return "…" + digits.substring(0, 2) + "-" + digits.substring(2)
    }

    /**
     * Короткая подпись для кнопки.
     * Предпочитает осмысленную метку из книги, откатывается на цифры.
     *
     * @param label метка типа номера («Рабочий», «Мобильный»)
     * @param allLabels все метки абонента — нужны, чтобы понять,
     *        различают ли они номера вообще
     */
    fun chipLabel(number: String, label: String?, allLabels: List<String>): String {
        val labelIsUseful = !label.isNullOrBlank() &&
            // Метка бесполезна, если у всех номеров она одинаковая:
            // три «Мобильный» ничего не различают
            allLabels.count { it == label } == 1
        return if (labelIsUseful) label!! else shortLabel(number)
    }
}
