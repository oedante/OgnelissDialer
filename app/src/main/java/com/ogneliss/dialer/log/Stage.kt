package com.ogneliss.dialer.log

import android.util.Log

/**
 * ОТМЕТКА ТЕКУЩЕГО ЭТАПА РАБОТЫ.
 *
 * ══════════════════════════════════════════════════════════════════════════
 * ЗАЧЕМ ЭТО НУЖНО
 * ══════════════════════════════════════════════════════════════════════════
 * Бывают падения, после которых в logcat пусто: процесс убит системой,
 * буфер логов переполнен другим приложением, или сбой произошёл в потоке,
 * чей стек не попал в отчёт.
 *
 * В такой ситуации единственное, что помогает, — знать, ЧТО приложение
 * делало последним. Отметка этапа стоит копейки, пишется без блокировок
 * и переживает падение: перехватчик записывает её в файл вместе со стеком,
 * а при следующем запуске приложение сообщает, на чём оборвалось
 * в прошлый раз.
 *
 * ── Почему не логировать каждый шаг ────────────────────────────────────────
 * Подробный лог тонет в собственном объёме: при разборе приходится
 * прокручивать тысячи строк. Отметка же всегда одна и отвечает
 * на единственный нужный вопрос.
 * ══════════════════════════════════════════════════════════════════════════
 */
object Stage {

    private const val TAG = "Stage"

    /**
     * Текущий этап.
     *
     * @Volatile обязателен: пишется из корутин на разных диспетчерах,
     * читается из обработчика падений в чужом потоке.
     */
    @Volatile
    var current: String = "startup"
        private set

    /** Этап, на котором приложение упало в прошлый раз. */
    @Volatile
    var previousCrashStage: String? = null
        internal set

    fun set(stage: String) {
        current = stage
        // В logcat пишем на уровне отладки: в release эти строки
        // не попадают и не занимают буфер
        Log.d(TAG, stage)
    }

    /** Строка для отчёта о падении. */
    fun describe(): String = "Этап: $current"
}
