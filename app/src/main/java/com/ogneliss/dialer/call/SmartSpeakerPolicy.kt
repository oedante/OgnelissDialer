package com.ogneliss.dialer.call

/**
 * ПОЛИТИКА АВТОМАТИЧЕСКОЙ ГРОМКОЙ СВЯЗИ.
 *
 * Назначение: решить, куда направить звук во время разговора,
 * по показаниям датчиков.
 *
 * Чистая логика без Android — покрыта тестами. Проверять это вручную
 * означало бы звонить кому-то и класть телефон на стол в разных позах.
 *
 * ── Идея ───────────────────────────────────────────────────────────────────
 * Телефон у уха → разговорный динамик. Телефон положили на стол экраном
 * вверх → громкая связь. Подняли обратно → снова динамик.
 *
 * ── Что определяют датчики ─────────────────────────────────────────────────
 * Датчик приближения: закрыт (у уха) или свободен.
 * Акселерометр: ось Z показывает, лежит ли устройство горизонтально.
 *   z ≈ +9.8 — экран вверх, лежит на столе
 *   z ≈ 0    — вертикально, в руке или у уха
 *   z ≈ -9.8 — экраном вниз
 *
 * ── Почему нужны задержка и гистерезис ─────────────────────────────────────
 * Без них переключение начинает «дребезжать»: рука дрожит, датчик
 * приближения на границе, и звук скачет между динамиками несколько раз
 * в секунду. Это хуже, чем полное отсутствие функции.
 *
 * Поэтому решение принимается только если состояние держится устойчиво,
 * а пороги для включения и выключения РАЗНЫЕ.
 *
 * ── Когда функция обязана молчать ──────────────────────────────────────────
 * • Подключена гарнитура — звук уже идёт куда надо, вмешиваться нельзя
 * • Пользователь сам нажал кнопку динамика — его выбор важнее датчиков
 *   до конца разговора
 * • Вызов ещё не активен (гудки, удержание)
 */
object SmartSpeakerPolicy {

    /** Куда направить звук. */
    enum class Route { EARPIECE, SPEAKER, UNCHANGED }

    /**
     * Порог «лежит горизонтально». 7.0 м/с² по оси Z — это наклон
     * примерно до 45°, то есть телефон лежит на столе или на ладони,
     * а не стоит в подставке.
     */
    const val FLAT_THRESHOLD = 7.0f

    /**
     * Порог возврата, заведомо ниже порога включения. Разные значения
     * и есть гистерезис: чтобы выключить громкую связь, телефон нужно
     * поднять ощутимо, а не просто качнуть.
     */
    const val UPRIGHT_THRESHOLD = 4.0f

    /**
     * Сколько состояние должно продержаться, прежде чем переключать.
     * 800 мс: человек кладёт телефон примерно за полсекунды,
     * а случайное дрожание длится меньше.
     */
    const val STABLE_DURATION_MS = 800L

    /** Показания датчиков и контекст вызова. */
    data class SensorState(
        /** Ускорение по оси Z, м/с². */
        val accelerationZ: Float,
        /** Датчик приближения закрыт — телефон у уха или в кармане. */
        val proximityNear: Boolean,
        /** Сколько миллисекунд состояние держится неизменным. */
        val stableForMs: Long,
        /** Сейчас включена громкая связь. */
        val speakerOn: Boolean,
        /** Подключена проводная или Bluetooth-гарнитура. */
        val headsetConnected: Boolean,
        /** Пользователь вручную переключал звук в этом разговоре. */
        val manualOverride: Boolean,
        /** Вызов активен (не гудки и не удержание). */
        val callActive: Boolean
    )

    fun decide(state: SensorState): Route {
        // Гарнитура: звук уже идёт куда надо
        if (state.headsetConnected) return Route.UNCHANGED

        // Ручной выбор пользователя важнее датчиков
        if (state.manualOverride) return Route.UNCHANGED

        // До соединения переключать нечего
        if (!state.callActive) return Route.UNCHANGED

        // Состояние ещё не устоялось — ждём
        if (state.stableForMs < STABLE_DURATION_MS) return Route.UNCHANGED

        // Телефон у уха: датчик приближения перекрыт
        if (state.proximityNear) {
            return if (state.speakerOn) Route.EARPIECE else Route.UNCHANGED
        }

        val lyingFlat = state.accelerationZ >= FLAT_THRESHOLD
        val heldUpright = state.accelerationZ <= UPRIGHT_THRESHOLD

        return when {
            // Положили на стол экраном вверх, датчик свободен
            lyingFlat && !state.speakerOn -> Route.SPEAKER
            // Подняли — возвращаем разговорный динамик
            heldUpright && state.speakerOn -> Route.EARPIECE
            // Промежуточное положение: не трогаем, это и есть гистерезис
            else -> Route.UNCHANGED
        }
    }

    /**
     * Стоит ли вообще подписываться на датчики.
     * Если функция выключена или подключена гарнитура, датчики можно
     * не слушать — это экономит батарею во время разговора.
     */
    fun shouldObserveSensors(enabled: Boolean, headsetConnected: Boolean): Boolean =
        enabled && !headsetConnected
}
