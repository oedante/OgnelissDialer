package com.ogneliss.dialer.call

import android.telecom.Call
import androidx.compose.runtime.staticCompositionLocalOf

/**
 * ПОДПИСИ СОСТОЯНИЯ НА ЭКРАНЕ ВЫЗОВА (2.9.7).
 *
 * Письмо пользователя, 24.11.2026: «добавьте, пожалуйста, возможность
 * показывать или скрывать подписи состояния на экране входящего и текущего
 * вызова — „Входящий“, „Вызов“, — оставив только таймер».
 *
 * Настройка «Подписи состояния вызова» (Экран вызова → расширенные,
 * Prefs.callStatusLabels, по умолчанию — показывать). Выключена — нет
 * обычных подписей «Входящий вызов» и «Соединение…». Остаются:
 * • таймер разговора — о нём и просили;
 * • «На удержании» и «Вызов завершён» — они сообщают то, чего иначе
 *   не видно: собеседник вас не слышит или уже положил трубку.
 *
 * ── Скрыта только видом ────────────────────────────────────────────────────
 * Плашка прозрачна, но место за ней остаётся: иначе при ответе, когда
 * появляется таймер, имя и портрет сдвигались бы. TalkBack по-прежнему
 * произносит состояние — настройка про вид, а не про то, что человек узнает.
 */
internal object CallStatusLabels {

    /** Видна ли плашка состояния [state] при настройке [labelsOn]. */
    fun shown(state: Int, labelsOn: Boolean): Boolean = labelsOn || !isRoutine(state)

    /** Обычные этапы, о которых и так понятно по экрану: звонят вам или звоните вы. */
    fun isRoutine(state: Int): Boolean = state == Call.STATE_RINGING ||
        state == Call.STATE_DIALING ||
        state == Call.STATE_CONNECTING
}

/**
 * Настройка «Подписи состояния вызова» для экрана вызова и псевдозвонка:
 * задают InCallActivity и FakeCallActivity, по умолчанию — показывать.
 */
internal val LocalCallStatusLabels = staticCompositionLocalOf { true }
