package com.ogneliss.dialer.call

import androidx.compose.runtime.setValue
import androidx.compose.runtime.mutableStateOf
import androidx.compose.runtime.getValue
import com.ogneliss.dialer.data.NotesRepository
import com.ogneliss.dialer.data.SpamMarkType
import com.ogneliss.dialer.data.SpamMarksRepository
import com.ogneliss.dialer.log.Logger
import com.ogneliss.dialer.util.PhoneFormatter
import kotlinx.coroutines.CoroutineScope
import kotlinx.coroutines.Job
import kotlinx.coroutines.delay
import kotlinx.coroutines.launch

/**
 * ЗАМЕТКА ВО ВРЕМЯ РАЗГОВОРА.
 *
 * ══════════════════════════════════════════════════════════════════════════
 * ЗАЧЕМ ПИСАТЬ ИМЕННО ВО ВРЕМЯ ЗВОНКА
 * ══════════════════════════════════════════════════════════════════════════
 * Договорённости забываются за минуты. «Привезут во вторник после
 * четырёх», «счёт на оплату пришлёт Марина», «перезвонить после 15:00» —
 * всё это произносится один раз, и записать это нужно тогда же.
 *
 * Экран после звонка помогает, но не всегда: разговор может длиться
 * двадцать минут, и к концу начало уже забылось. Плюс после звонка
 * человек часто сразу переключается на другое дело.
 *
 * ── Почему сохранение автоматическое ───────────────────────────────────────
 * Кнопки «Сохранить» здесь нет намеренно. Во время разговора внимание
 * занято, и требовать подтверждения — верный способ потерять текст:
 * человек допишет мысль, положит трубку, и заметка исчезнет вместе
 * с экраном вызова.
 *
 * Текст сохраняется сам через паузу после последнего нажатия и ещё раз
 * при завершении вызова.
 *
 * ── Почему с задержкой, а не на каждый символ ──────────────────────────────
 * Запись в базу на каждую букву — это обращение к диску десятки раз
 * в секунду во время разговора, когда система и так занята обработкой
 * звука. Полторы секунды тишины после ввода — достаточный признак того,
 * что мысль закончена.
 * ══════════════════════════════════════════════════════════════════════════
 */
class InCallNoteState(
    private val notes: NotesRepository,
    /*
     * Отметки «спам» и «мошенники» — отдельное хранилище с 1.1.1.
     * Фишки на экране вызова пишут туда, а не в заметку: разбор
     * в SpamMarkEntity.
     */
    private val marks: SpamMarksRepository,
    private val scope: CoroutineScope
) {

    private companion object {
        const val TAG = "InCallNote"

        /**
         * Пауза перед сохранением. Полторы секунды: меньше — начнём
         * писать в базу посреди слова, больше — рискуем не успеть
         * до завершения вызова.
         */
        const val SAVE_DELAY_MS = 1500L
    }

    private var saveJob: Job? = null
    private var currentNumber: String? = null

    /**
     * ТЕКСТ ЗАМЕТКИ КАК СОСТОЯНИЕ COMPOSE.
     *
     * ══════════════════════════════════════════════════════════════════════
     * ПОЧЕМУ mutableStateOf, А НЕ ОБЫЧНОЕ ПОЛЕ
     * ══════════════════════════════════════════════════════════════════════
     * Было обычное поле класса. Присваивание в него ничего не сообщает
     * Compose: экран не знает, что значение изменилось, и продолжает
     * рисовать прежнее.
     *
     * Со стороны это выглядело так, будто поле ввода не работает вовсе:
     * человек нажимает клавиши, символы уходят в onTextChange, значение
     * в объекте меняется — а на экране пусто. Ввести текст было нельзя.
     *
     * mutableStateOf делает поле наблюдаемым: любое присваивание
     * перерисовывает то, что его читает.
     *
     * ── Про загрузку существующей заметки ──────────────────────────────────
     * Она приходит из базы асинхронно, уже после первой отрисовки.
     * С обычным полем текст не появился бы и там — ещё одна причина,
     * по которой поле должно быть состоянием.
     */
    var text: String by mutableStateOf("")
        private set

    /**
     * ВЫБРАННЫЕ МЕТКИ.
     *
     * Состояние Compose по той же причине, что и текст: обычное поле
     * не сообщает об изменении, и нажатая метка не отмечалась бы
     * на экране.
     *
     * Метки сохраняются сразу, а не по кнопке: их ставят одним
     * нажатием во время разговора, и ждать сохранения текста незачем —
     * текста может не быть вовсе.
     */
    var tags: Set<String> by mutableStateOf(emptySet())
        private set

    /**
     * Переключение метки.
     *
     * Сохраняется немедленно: человек услышал предложение кредита,
     * отметил «спам» и положил трубку — экран закроется раньше, чем
     * сработает отложенное сохранение текста.
     */
    fun toggleTag(key: String) {
        // Номер берётся из currentNumber: отдельного поля e164
        // в классе нет, оно вычисляется при каждом обращении
        val number = currentNumber ?: return

        /*
         * Отметка одна: повторное нажатие на выбранную снимает её,
         * нажатие на другую — заменяет. Номер не может быть
         * одновременно спамом и мошенниками.
         */
        val type = SpamMarkType.fromKey(key) ?: return
        val selected = key in tags
        tags = if (selected) emptySet() else setOf(key)

        scope.launch {
            runCatching {
                val e164 = PhoneFormatter.toE164(number)
                if (selected) marks.unmark(e164) else marks.mark(e164, type)
            }.onFailure { Logger.w(TAG, "Не удалось сохранить отметку", it) }
        }
    }

    /**
     * Загрузка существующей заметки.
     *
     * Если про этот номер уже что-то записано, показываем текст:
     * человек дополняет запись, а не начинает с чистого листа
     * и не затирает прежнюю.
     */
    fun load(number: String) {
        currentNumber = number
        scope.launch {
            runCatching {
                val e164 = PhoneFormatter.toE164(number)

                // Одно чтение на оба поля: заметка и метки лежат
                // в одной записи, и второй запрос был бы лишним
                val loaded = notes.get(e164)
                text = loaded?.note.orEmpty()

                // Отметка — из своего хранилища: человек мог поставить
                // её раньше, и фишка должна быть видна выбранной
                tags = setOfNotNull(marks.get(e164)?.type?.key)
            }.onFailure { Logger.w(TAG, "Не удалось прочитать заметку", it) }
        }
    }

    /**
     * Ввод текста.
     *
     * Сохранение откладывается: предыдущая отложенная задача отменяется,
     * и отсчёт начинается заново. Так запись в базу происходит один раз
     * после окончания ввода, а не на каждую букву.
     */
    fun onTextChange(value: String) {
        text = value

        saveJob?.cancel()
        saveJob = scope.launch {
            delay(SAVE_DELAY_MS)
            save()
        }
    }

    /**
     * Немедленное сохранение.
     *
     * Вызывается при завершении вызова: экран вот-вот исчезнет,
     * и ждать паузу больше нельзя.
     */
    fun saveNow() {
        saveJob?.cancel()
        scope.launch { save() }
    }

    private suspend fun save() {
        val number = currentNumber ?: return
        val e164 = PhoneFormatter.toE164(number)

        runCatching {
            val trimmed = text.trim()
            if (trimmed.isEmpty()) {
                // Пустой текст удаляет заметку, а не сохраняет пустоту:
                // иначе стёртая заметка продолжала бы занимать место
                // и попадать в поиск
                notes.delete(e164)
            } else {
                // Метки сохраняем прежние: во время разговора их
                // не меняют, а затирать чужую работу нельзя
                val existing = notes.get(e164)
                // Метки заметки берутся из неё самой, а не из фишек:
                // фишки на этом экране — отметка о спаме, и в заметку
                // она попадать не должна
                notes.save(e164, trimmed, existing?.tags.orEmpty(), existing?.customLabel)
            }
            Logger.d(TAG, "Заметка сохранена для ${Logger.mask(e164)}")
        }.onFailure { Logger.w(TAG, "Не удалось сохранить заметку", it) }
    }
}
