package com.ogneliss.dialer.call

/**
 * СЕРВИСНЫЕ КОДЫ НАБОРА — КОГДА СРАБАТЫВАТЬ (2.9.1).
 *
 * Форум, som_bbs: «"secret code" обрабатывать не умеет? В планах есть
 * организовать это?». Коды обрабатывались с 2.1.0 (CallActions.handleSecretCode),
 * но только по кнопке вызова. Системная звонилка и звонилки производителей
 * срабатывают сразу, как набран последний символ кода, — этого и ждут:
 * набрал *#*#4636#*#* — открылось меню «Тестирование», без «звонка».
 *
 * Здесь — только правило «код набран целиком», чистый Kotlin (ServiceCodesTest).
 */
object ServiceCodes {

    /** *#*#цифры#*#* — код для приложений (сервисные меню, отладка). */
    val SECRET = Regex("""\*#\*#(\d+)#\*#\*""")

    /** *#06# — IMEI/MEID: показывает система (TelecomManager.handleMmi). */
    const val IMEI = "*#06#"

    /** Набранное — целый сервисный код: обработать сразу, без кнопки вызова. */
    fun isComplete(query: String): Boolean {
        val q = query.trim()
        return q == IMEI || SECRET.matches(q)
    }
}
