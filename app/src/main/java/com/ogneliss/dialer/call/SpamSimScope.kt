package com.ogneliss.dialer.call

/**
 * ПРАВИЛА ЗАЩИТЫ ОТ СПАМА — ДЛЯ КАКОЙ SIM (2.9.8).
 *
 * Форум, Bublikov34: «можно ли сделать разделение настроек спама на разные
 * сим-карты?»; автор: «попробую в следующей версии сделать».
 *
 * Правила — «Блокировать скрытые номера», «…не из контактов», «…с метками»
 * и тихие часы — действуют на вызовы выбранной карты. На другую карту звонят
 * все, кроме явных списков: чёрный и белый списки приложения и системный
 * список блокировки Android работают для обеих — это решение о номере,
 * а не о карте. Пример: личная SIM — не принимать незнакомых, рабочая —
 * принимать всех.
 *
 * Карту вызова сказать нельзя (одна SIM, система не передала аккаунт) —
 * правила действуют, как без этой настройки: защита, которую включили,
 * не должна пропасть от недостатка сведений.
 */
enum class SpamSimScope {
    /** На всех картах — как было до 2.9.8, по умолчанию. */
    ALL,
    SIM1,
    SIM2;

    /** Действуют ли правила на вызов, пришедший в слот [slot] (0, 1; null — неизвестно). */
    fun covers(slot: Int?): Boolean = when (this) {
        ALL -> true
        SIM1 -> slot == null || slot == 0
        SIM2 -> slot == null || slot == 1
    }

    companion object {
        fun from(name: String?): SpamSimScope = entries.firstOrNull { it.name == name } ?: ALL
    }
}
