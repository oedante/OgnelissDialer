package com.ogneliss.dialer.call

import java.util.concurrent.ConcurrentHashMap

/**
 * ТИХИЕ ЧАСЫ ДЛЯ НЕЗНАКОМЫХ (1.8.0).
 *
 * ══════════════════════════════════════════════════════════════════════════
 * ЗАЧЕМ
 * ══════════════════════════════════════════════════════════════════════════
 * Автор, в списке функций для 1.8.0: «Тихие часы для незнакомых». Ночные
 * звонки с чужих номеров — почти всегда спам, ошибка или обзвон, и будят
 * они так же, как настоящие. Системный «Не беспокоить» решает это грубо:
 * глушит всех, кроме избранных, и его надо не забыть включить.
 *
 * Здесь мягче: в выбранные часы незнакомый звонок проходит БЕЗ ЗВУКА —
 * не отклоняется, а остаётся в журнале пропущенным с пометкой «Без звука —
 * тихие часы». Утром видно, кто звонил, и можно перезвонить.
 *
 * ── Срочное прорывается ────────────────────────────────────────────────────
 * Тот же номер перезвонил за 15 минут — телефон звонит. Так работает
 * «повторный вызов» в системном «Не беспокоить», и смысл тот же: случайный
 * спам второй раз подряд не звонит, человек с бедой — звонит.
 *
 * Номера из контактов и из белого списка звонят всегда: правило проверяется
 * в SpamPolicy после них.
 *
 * ── Значения ───────────────────────────────────────────────────────────────
 * Готовые промежутки, а не два поля времени: «с 22 до 8» и «с 23 до 7»
 * покрывают почти всех, а окно выбора часов и минут — лишние три касания
 * для настройки, которую задают один раз. «Круглосуточно» — для тех, кому
 * незнакомые не звонят по делу вовсе (но кто не хочет их блокировать).
 *
 * Хранится строкой: имена менять нельзя.
 */
enum class QuietHours(
    /** Начало, минуты от полуночи; конец не включается. */
    val startMinute: Int,
    val endMinute: Int
) {
    OFF(0, 0),
    NIGHT_22_08(22 * 60, 8 * 60),
    NIGHT_23_07(23 * 60, 7 * 60),
    ALWAYS(0, 24 * 60);

    /**
     * Попадает ли минута суток в тихие часы.
     *
     * Ночные промежутки переходят через полночь: начало больше конца,
     * и «внутри» — это «после начала ИЛИ до конца».
     */
    fun contains(minuteOfDay: Int): Boolean = when {
        this == OFF -> false
        startMinute <= endMinute -> minuteOfDay in startMinute until endMinute
        else -> minuteOfDay >= startMinute || minuteOfDay < endMinute
    }

    companion object {
        val DEFAULT = OFF

        /** Окно «перезвонил — значит срочно». */
        const val REPEAT_WINDOW_MS = 15 * 60 * 1000L

        fun from(name: String?): QuietHours = entries.firstOrNull { it.name == name } ?: DEFAULT
    }
}

/**
 * МЕТКА «ЭТОТ ВХОДЯЩИЙ — ТИХИЙ» ОТ ПРОВЕРКИ ДО ЭКРАНА ВЫЗОВА.
 *
 * Решение принимает служба проверки вызовов (OgnelissCallScreeningService):
 * у неё есть всё — контакты, белый список, время, прошлые звонки. Но
 * заглушить звонок сама она может, только держа роль определителя,
 * а её у многих держит Яндекс или Касперский.
 *
 * Поэтому решение передаётся дальше, службе вызовов: та не открывает
 * экран вызова (иначе он зажёг бы экран посреди ночи), показывает тихое
 * уведомление и глушит звонок системы. Обе службы — в одном процессе,
 * и метки в памяти достаточно: проверка всегда идёт раньше, чем вызов
 * доходит до экрана.
 */
object QuietCallGate {

    /** Метка старше этого — не про текущий вызов. */
    private const val TTL_MS = 60_000L

    private val marks = ConcurrentHashMap<String, Long>()

    /** Проверка решила: этот вызов — тихий. */
    fun mark(e164: String, now: Long = System.currentTimeMillis()) {
        marks[e164] = now
    }

    /** Служба вызовов забирает метку: true — вызов тихий. */
    fun take(e164: String, now: Long = System.currentTimeMillis()): Boolean {
        val at = marks.remove(e164) ?: return false
        return now - at <= TTL_MS
    }
}
